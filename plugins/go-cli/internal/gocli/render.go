// このファイルは cli.go のテキスト（docs/plugin-go-cli.md「出力」「引数の解釈」「実行と表示」「使い方の表示」）。検査（emit.go）を
// 通った入力だけを描く。
//
// cli.go は自分のパッケージ（cli）なので、非公開の名前に前置きの決まりはない（docs/plugin-go.md「相乗りのファイル」）。ただし、
// import する名前空間のパッケージの名前（小文字と数字だけ）と当たらないように、パッケージの非公開の名前は、どれも大文字を含む形に
// する: コマンドごとの run<Op> / fail<Op> / usage<Op> と、補助の cli<名前>（コマンドごとの名前と当たらないように、前置きを分ける）。

// runtimePath は、生成したコードが import する runtime パッケージ（*runtime.ValidationError。docs/plugin-go-valid.md「runtime」）。
const runtimePath = "github.com/mew-ton/hozo/runtime"

// file は、描いている途中の cli.go。
type file struct {
	g  *generator
	im *golang.Imports
	// entry は、N の入口のパッケージを修飾する名前。
	entry string
	// reserved は、このファイルが import するパッケージの名前（一度目に描いて決めたもの）。局所の名前が避ける。
	reserved map[string]bool
	// std は、使った標準ライブラリと runtime の import パス。spaces は、型を書いた別の名前空間。
	std    map[string]bool
	spaces map[string]bool
	// 補助のうち、コマンドが使ったもの（使うものだけを出す）。
	usesLookup, usesLookupArg, usesPtr, usesValidation bool
}

func (g *generator) newFile() *file {
	return &file{g: g, im: golang.NewImports(g.view, g.layout, g.root, false), reserved: map[string]bool{}, std: map[string]bool{}, spaces: map[string]bool{}}
}

// local は、関数の中の局所の名前。このファイルが import するパッケージの名前と当たれば、当たらなくなるまで末尾に _ を足す
// （docs/plugin-go.md「名前」の「局所の名前」と同じ扱い）。
func (f *file) local(name string) string {
	for f.reserved[name] {
		name += "_"
	}
	return name
}

// pkg は、標準ライブラリか runtime のパッケージを import に足して、その名前を返す（名前は変わらない。
// docs/plugin-go.md「パッケージと import パス」）。
func (f *file) pkg(importPath string) string {
	f.std[importPath] = true
	return f.im.Add(importPath, path.Base(importPath))
}

// ns は、N の入口のパッケージを修飾する名前。
func (f *file) ns() string {
	if f.entry == "" {
		f.entry = f.im.Add(f.g.layout.EntryPath, f.g.layout.EntryName)
	}
	return f.entry
}

// decl は、宣言 fqn（型、例外）を、このファイルから書く名前: N のものは入口のパッケージで、別の名前空間のものは、その型の置き場の
// 入口のパッケージで修飾する。
func (f *file) decl(fqn string) string {
	space := f.g.declNS[fqn]
	name := golang.TypeName(fqn, space)
	if space == f.g.view.Viewer {
		return f.ns() + "." + name
	}
	f.spaces[space] = true
	return f.im.Qualifier(space) + name
}

// render は cli.go の全体を作り、go/format で整形する。import の名前を文書の決まりの順で決めるために、二度描く
// （docs/plugin-go.md「パッケージと import パス」の「import の名前」）: 一度目で、使う import の集まりを知り、二度目は、標準ライブラリと
// runtime を先に、その後に名前空間のパッケージ（N の入口を含む）を FQN の辞書順に足した名前で描く。
func (g *generator) render(commands []command) (string, error) {
	first := g.newFile()
	first.draw(commands)
	second := g.newFile()
	var std []string
	for p := range first.std {
		std = append(std, p)
	}
	sort.Strings(std)
	for _, p := range std {
		second.pkg(p)
	}
	spaces := []string{g.view.Viewer}
	for space := range first.spaces {
		spaces = append(spaces, space)
	}
	sort.Strings(spaces)
	for _, space := range spaces {
		if space == g.view.Viewer {
			second.ns()
		} else {
			second.im.Qualifier(space)
		}
	}
	for _, name := range second.im.Names() {
		second.reserved[name] = true
	}
	text := second.draw(commands)
	if err := second.im.Err(); err != nil {
		return "", fmt.Errorf("%s: %w（CFG-22 が通したはずのもの）", OutputPath, err)
	}
	src, err := format.Source([]byte(text))
	if err != nil {
		return "", fmt.Errorf("生成した %s を整形できない（生成器の不具合）: %w\n%s", OutputPath, err, text)
	}
	return string(src), nil
}

// draw は、ファイルのテキスト（整形前）を作る: ヘッダ、パッケージのコメント、package 節、import、Presenter と JSONPresenter、
// Main と全体の使い方、コマンドごとの関数、補助。
func (f *file) draw(commands []command) string {
	presenter := f.presenter()
	main := f.main(commands)
	var each strings.Builder
	for i := range commands {
		each.WriteString(f.command(&commands[i]))
	}
	helpers := f.helpers()
	var b strings.Builder
	b.WriteString("// Code generated by hozoc " + TranspilerName + " " + plugin.Version + "; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "// Package %s は名前空間 %s のコマンドライン: 引数の解釈、op の呼び出し、結果と例外の表示、終了コード。\n", DirName, f.g.view.Viewer)
	b.WriteString("//\n// 人が書く main は、実装を組み立てて\n//\n")
	fmt.Fprintf(&b, "//\tos.Exit(%s.Main(ctx, ops, p, os.Args[1:], os.Getenv, os.Stdout, os.Stderr))\n", DirName)
	b.WriteString("//\n// を呼ぶだけ。\n")
	b.WriteString("package " + DirName + "\n\n")
	b.WriteString(f.im.Render())
	b.WriteString("\n")
	b.WriteString(presenter)
	b.WriteString(main)
	b.WriteString(each.String())
	b.WriteString(helpers)
	return b.String()
}

// presenter は Presenter、Failure、JSONPresenter（docs/plugin-go-cli.md「出力」「実行と表示」）。
func (f *file) presenter() string {
	io, json, fmt_ := f.pkg("io"), f.pkg("encoding/json"), f.pkg("fmt")
	return `// Presenter は結果と例外の表示。既定は JSON（JSONPresenter）。
type Presenter interface {
	// Present は成功の結果を w（標準出力）に出す。command はサブコマンドの名前、input は解釈した入力（引数のない op なら nil）、
	// result は op の結果（値を返さない op なら nil）。
	Present(w ` + io + `.Writer, command string, input any, result any) error
	// PresentError は例外を w（標準エラー）に出す。
	PresentError(w ` + io + `.Writer, command string, input any, f Failure) error
}

// Failure は例外の内容。Name は例外の FQN、Value は運ぶ値（なければ nil）、Err は op が返した error そのもの
// （Presenter がメッセージに使える）。Main が、例外の値の型を見分けて入れる。宣言にない例外なら Name は空で Err だけ。
type Failure struct {
	Name  string
	Value any
	Err   error
}

// JSONPresenter は結果と例外を JSON で出す、既定の Presenter。
type JSONPresenter struct{}

// Present は result を json.MarshalIndent(result, "", "  ") で w に出す。nil なら何も出さない。
func (JSONPresenter) Present(w ` + io + `.Writer, command string, input any, result any) error {
	if result == nil {
		return nil
	}
	b, err := ` + json + `.MarshalIndent(result, "", "  ")
	if err != nil {
		return err
	}
	_, err = ` + fmt_ + `.Fprintln(w, string(b))
	return err
}

// PresentError は、Name があれば {"error": "<Name>", "value": <Value>}（Value が nil なら value を省く）を、
// なければ {"error": "<Err.Error()>"} を w に出す。
func (JSONPresenter) PresentError(w ` + io + `.Writer, command string, input any, f Failure) error {
	body := struct {
		Error string ` + "`json:\"error\"`" + `
		Value any    ` + "`json:\"value,omitempty\"`" + `
	}{Error: f.Name, Value: f.Value}
	if f.Name == "" {
		body.Error, body.Value = "unknown error", nil
		if f.Err != nil {
			body.Error = f.Err.Error()
		}
	}
	b, err := ` + json + `.MarshalIndent(body, "", "  ")
	if err != nil {
		return err
	}
	_, err = ` + fmt_ + `.Fprintln(w, string(b))
	return err
}

`
}

// signature は、Main と run<Op> が共有する引数の名前（局所の名前）。
type signature struct{ ctx, ops, p, prog, args, env, stdout, stderr string }

func (f *file) signature() signature {
	return signature{f.local("ctx"), f.local("ops"), f.local("p"), f.local("prog"), f.local("args"), f.local("env"), f.local("stdout"), f.local("stderr")}
}

// main は Main と、全体の使い方（docs/plugin-go-cli.md「出力」「引数の解釈」「使い方の表示」）。
func (f *file) main(commands []command) string {
	s := f.signature()
	context, io, fmt_ := f.pkg("context"), f.pkg("io"), f.pkg("fmt")
	var b strings.Builder
	b.WriteString("// Main は引数を解釈して ops の op を呼び、結果を p で表示し、終了コードを返す。ctx は op にそのまま渡す。\n")
	b.WriteString("// args は os.Args[1:]（プログラム名を含まない）。env は環境変数の値を返す関数（os.Getenv。nil なら環境変数を見ない）。\n")
	fmt.Fprintf(&b, "// 終了コード: 成功 0、使い方の誤り 64、@cli.exitCode の付いた例外はその値、それ以外の例外と表示の失敗 %d。\n", defaultExitCode)
	fmt.Fprintf(&b, "func Main(%s %s.Context, %s %s.Ops, %s Presenter, %s []string, %s func(string) string, %s, %s %s.Writer) int {\n",
		s.ctx, context, s.ops, f.ns(), s.p, s.args, s.env, s.stdout, s.stderr, io)
	fmt.Fprintf(&b, "%s := cliProgramName()\n", s.prog)
	fmt.Fprintf(&b, "if len(%s) == 0 {\n%s.Fprint(%s, cliUsage(%s))\nreturn 64\n}\n", s.args, fmt_, s.stderr, s.prog)
	// help は、コマンドの名前より先に見る（help という名前のコマンドがあっても、使い方を出す）
	fmt.Fprintf(&b, "if %s[0] == \"help\" || %s[0] == \"--help\" || %s[0] == \"-h\" {\n%s.Fprint(%s, cliUsage(%s))\nreturn 0\n}\n", s.args, s.args, s.args, fmt_, s.stdout, s.prog)
	fmt.Fprintf(&b, "switch %s[0] {\n", s.args)
	for i := range commands {
		c := &commands[i]
		fmt.Fprintf(&b, "case %s:\nreturn run%s(%s, %s, %s, %s, %s[1:], %s, %s, %s)\n", strconv.Quote(c.name), c.method, s.ctx, s.ops, s.p, s.prog, s.args, s.env, s.stdout, s.stderr)
	}
	b.WriteString("}\n")
	fmt.Fprintf(&b, "return cliUsageError(%s, %s, cliUsage(%s), %s.Sprintf(\"unknown command %%q\", %s[0]))\n}\n\n", s.stderr, s.prog, s.prog, fmt_, s.args)

	var rows [][2]string
	for i := range commands {
		rows = append(rows, [2]string{commands[i].name, commands[i].summary})
	}
	var usage strings.Builder
	usage.WriteString(" <command> [flags]\n\ncommands:\n")
	writeRows(&usage, rows)
	b.WriteString("// cliUsage は全体の使い方。\n")
	fmt.Fprintf(&b, "func cliUsage(prog string) string {\nreturn \"usage: \" + prog + %s\n}\n\n", strconv.Quote(usage.String()))
	return b.String()
}

// command は、サブコマンド一つの run<Op>、fail<Op>、usage<Op>（docs/plugin-go-cli.md「引数の解釈」「実行と表示」）。
func (f *file) command(c *command) string {
	s := f.signature()
	context, io, fmt_ := f.pkg("context"), f.pkg("io"), f.pkg("fmt")
	m := c.input
	usage := "usage" + c.method + "(" + s.prog + ")"
	flags, pos, help, err, in := f.local("flags"), f.local("pos"), f.local("help"), f.local("err"), f.local("in")
	usageError := func(message string) string {
		return fmt.Sprintf("return cliUsageError(%s, %s, %s, %s)\n", s.stderr, s.prog, usage, message)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// run%s はサブコマンド %s（op %s）。\n", c.method, c.name, c.op.Name)
	fmt.Fprintf(&b, "func run%s(%s %s.Context, %s %s.Ops, %s Presenter, %s string, %s []string, %s func(string) string, %s, %s %s.Writer) int {\n",
		c.method, s.ctx, context, s.ops, f.ns(), s.p, s.prog, s.args, s.env, s.stdout, s.stderr, io)

	// フラグと位置引数に分ける。フラグの表は、フラグ名 → boolean か
	var specs []string
	usesFlags, fixed, hasArray := false, 0, false
	if m != nil {
		for _, fd := range m.fields {
			if fd.flag != "" {
				specs = append(specs, fmt.Sprintf("%s: %v", strconv.Quote(fd.flag), fd.kind == kindBoolean))
			}
			switch {
			case fd.array:
				hasArray = true
			case fd.arg:
				fixed++
			default:
				usesFlags = true
			}
		}
	}
	table := "nil"
	if len(specs) > 0 {
		table = "map[string]bool{" + strings.Join(specs, ", ") + "}"
	}
	if !usesFlags {
		flags = "_"
	}
	fmt.Fprintf(&b, "%s, %s, %s, %s := cliParseArgs(%s, %s)\n", flags, pos, help, err, s.args, table)
	fmt.Fprintf(&b, "if %s != nil {\n%s}\n", err, usageError(err+".Error()"))
	fmt.Fprintf(&b, "if %s {\n%s.Fprint(%s, %s)\nreturn 0\n}\n", help, fmt_, s.stdout, usage)
	if !hasArray {
		fmt.Fprintf(&b, "if len(%s) > %d {\n%s}\n", pos, fixed,
			usageError(fmt.Sprintf("%s.Sprintf(\"too many arguments: %%d given, at most %d expected\", len(%s))", fmt_, fixed, pos)))
	}

	// 入力の初めの値と、フィールドごとの値
	input := "nil"
	if m != nil {
		input = in
		if m.hasDefault {
			space := f.g.declNS[m.decl.Name]
			name := "New" + golang.TypeName(m.decl.Name, space)
			if space == f.g.view.Viewer {
				fmt.Fprintf(&b, "%s := %s.%s()\n", in, f.ns(), name)
			} else {
				f.spaces[space] = true
				fmt.Fprintf(&b, "%s := %s%s()\n", in, f.im.Qualifier(space), name)
			}
		} else {
			fmt.Fprintf(&b, "var %s %s\n", in, f.decl(m.decl.Name))
		}
		index := 0
		for _, fd := range m.fields {
			b.WriteString(f.field(fd, s, flags, pos, in, usageError, &index))
		}
		// 制約の検査
		if m.validate {
			f.usesValidation = true
			fmt.Fprintf(&b, "if %s := %s.Validate(); %s != nil {\nreturn cliUsageError(%s, %s, \"\", \"invalid input: \"+cliValidationMessage(%s))\n}\n",
				err, in, err, s.stderr, s.prog, err)
		}
	}

	// op を呼んで、結果を表示する
	call := fmt.Sprintf("%s.%s(%s", s.ops, c.method, s.ctx)
	if m != nil {
		call += ", " + in
	}
	call += ")"
	fail := fmt.Sprintf("return fail%s(%s, %s, %s, %s, %s)\n", c.method, s.p, s.prog, input, err, s.stderr)
	result := "nil"
	if c.void {
		fmt.Fprintf(&b, "if %s := %s; %s != nil {\n%s}\n", err, call, err, fail)
	} else {
		result = f.local("result")
		fmt.Fprintf(&b, "%s, %s := %s\nif %s != nil {\n%s}\n", result, err, call, err, fail)
	}
	fmt.Fprintf(&b, "if %s := %s.Present(%s, %s, %s, %s); %s != nil {\n%s.Fprintf(%s, \"%%s: %%v\\n\", %s, %s)\nreturn %d\n}\nreturn 0\n}\n\n",
		err, s.p, s.stdout, strconv.Quote(c.name), input, result, err, fmt_, s.stderr, s.prog, err, defaultExitCode)

	b.WriteString(f.fail(c, s))

	fmt.Fprintf(&b, "// usage%s は %s の使い方。\n", c.method, c.name)
	fmt.Fprintf(&b, "func usage%s(prog string) string {\nreturn \"usage: \" + prog + %s\n}\n\n", c.method, strconv.Quote(commandUsage(c)))
	return b.String()
}

// field は、フィールド一つの値の取り出しと変換（docs/plugin-go-cli.md「引数の解釈」）。index は、次の位置引数の番号。
func (f *file) field(fd *field, s signature, flags, pos, in string, usageError func(string) string, index *int) string {
	target := in + "." + golang.FieldName(fd.name)
	var b strings.Builder
	// 値の型にする式: 核の型ならそのまま、scalar なら、元の型で読んだ値を scalar の型にする
	convert := func(expr string) string {
		if r, isRef := fd.value.(ir.RefType); isRef {
			return f.decl(r.Target) + "(" + expr + ")"
		}
		return expr
	}
	if fd.array {
		rest := pos
		if *index > 0 {
			rest = fmt.Sprintf("%s[%d:]", pos, *index)
		}
		fmt.Fprintf(&b, "if len(%s) > %d {\n", pos, *index)
		if convert("v") == "v" {
			fmt.Fprintf(&b, "%s = %s\n", target, rest)
		} else {
			v := f.local("v")
			fmt.Fprintf(&b, "for _, %s := range %s {\n%s = append(%s, %s)\n}\n", v, rest, target, target, convert(v))
		}
		b.WriteString("}\n")
		return b.String()
	}

	// 誤りのメッセージで、値の出どころを指す言葉
	var label, what string
	switch {
	case fd.arg:
		label = argLabel(fd.name)
		what = "argument " + label
	case fd.flag != "":
		label = "--" + fd.flag
		what = "flag " + label
	default:
		label = fd.env
		what = "environment variable " + label
	}
	v, ok := f.local("v"), f.local("ok")
	if fd.arg {
		f.usesLookupArg = true
		fmt.Fprintf(&b, "if %s, %s := cliLookupArg(%s, %d, %s, %s); %s {\n", v, ok, pos, *index, s.env, strconv.Quote(fd.env), ok)
		*index++
	} else {
		f.usesLookup = true
		fmt.Fprintf(&b, "if %s, %s := cliLookup(%s, %s, %s, %s); %s {\n", v, ok, flags, strconv.Quote(fd.flag), s.env, strconv.Quote(fd.env), ok)
	}
	value := v
	if fd.kind != kindString {
		var parse string
		switch fd.kind {
		case kindBoolean:
			parse = fmt.Sprintf("%s.ParseBool(%s)", f.pkg("strconv"), v)
		case kindInt:
			parse = fmt.Sprintf("%s.ParseInt(%s, 10, 64)", f.pkg("strconv"), v)
		default:
			parse = fmt.Sprintf("%s.ParseFloat(%s, 64)", f.pkg("strconv"), v)
		}
		x, err := f.local("x"), f.local("err")
		fmt.Fprintf(&b, "%s, %s := %s\nif %s != nil {\n%s}\n", x, err, parse, err,
			usageError(fmt.Sprintf("%s.Sprintf(%s, %s)", f.pkg("fmt"), strconv.Quote("invalid value %q for "+label+": want "+fd.kind.label()), v)))
		value = x
	}
	if fd.optional {
		f.usesPtr = true
		fmt.Fprintf(&b, "%s = cliPtr(%s)\n", target, convert(value))
	} else {
		fmt.Fprintf(&b, "%s = %s\n", target, convert(value))
	}
	if fd.required {
		b.WriteString("} else {\n" + usageError(strconv.Quote("missing required "+what)))
	}
	b.WriteString("}\n")
	return b.String()
}

// fail は fail<Op>（docs/plugin-go-cli.md「実行と表示」の 3 と 4）: 例外を、Signature.exceptions の順に、errors.As で値の型を
// 見分けて Failure を作り、終了コードを決めてから、p.PresentError を呼ぶ。
func (f *file) fail(c *command, s signature) string {
	io, fmt_ := f.pkg("io"), f.pkg("fmt")
	input, err, fl, code := f.local("input"), f.local("err"), f.local("f"), f.local("code")
	var b strings.Builder
	fmt.Fprintf(&b, "// fail%s は %s の例外を、宣言の順に値の型で見分けて Failure を作り、終了コードを決めて p で表示する。\n", c.method, c.name)
	fmt.Fprintf(&b, "func fail%s(%s Presenter, %s string, %s any, %s error, %s %s.Writer) int {\n", c.method, s.p, s.prog, input, err, s.stderr, io)
	fmt.Fprintf(&b, "%s, %s := Failure{Err: %s}, %d\n", fl, code, err, defaultExitCode)
	if len(c.exceptions) > 0 {
		errors := f.pkg("errors")
		b.WriteString("var (\n")
		for i, e := range c.exceptions {
			fmt.Fprintf(&b, "%s %s\n", f.local("e"+strconv.Itoa(i)), f.decl(e.decl.Name))
		}
		b.WriteString(")\nswitch {\n")
		for i, e := range c.exceptions {
			v := f.local("e" + strconv.Itoa(i))
			fmt.Fprintf(&b, "case %s.As(%s, &%s):\n", errors, err, v)
			if e.decl.Value != nil {
				fmt.Fprintf(&b, "%s, %s = Failure{Name: %s, Value: %s.Value, Err: %s}, %d\n", fl, code, strconv.Quote(e.decl.Name), v, err, e.exitCode)
			} else {
				fmt.Fprintf(&b, "%s, %s = Failure{Name: %s, Err: %s}, %d\n", fl, code, strconv.Quote(e.decl.Name), err, e.exitCode)
			}
		}
		b.WriteString("}\n")
	}
	fmt.Fprintf(&b, "if %s := %s.PresentError(%s, %s, %s, %s); %s != nil {\n%s.Fprintf(%s, \"%%s: %%v\\n\", %s, %s)\nreturn %d\n}\nreturn %s\n}\n\n",
		err, s.p, s.stderr, strconv.Quote(c.name), input, fl, err, fmt_, s.stderr, s.prog, err, defaultExitCode, code)
	return b.String()
}

// helpers は、コマンドごとの関数の後ろの補助。cliProgramName、cliParseArgs、cliUsageError はいつも、ほかは使うものだけを出す。
func (f *file) helpers() string {
	os, filepath, strings_, fmt_, io := f.pkg("os"), f.pkg("path/filepath"), f.pkg("strings"), f.pkg("fmt"), f.pkg("io")
	var b strings.Builder
	b.WriteString(`// cliProgramName は、使い方に出すプログラム名（filepath.Base(os.Args[0])）。
func cliProgramName() string {
	if len(` + os + `.Args) > 0 && ` + os + `.Args[0] != "" {
		return ` + filepath + `.Base(` + os + `.Args[0])
	}
	return ` + strconv.Quote(golang.PackageName(f.g.view.Viewer)) + `
}

// cliParseArgs は args をフラグと位置引数に分ける。specs は、フラグ名 → boolean か。フラグは --name value か --name=value で、
// boolean は --name だけで true（値は取らない。--name=false は取れる）。同じフラグが二度あれば、後のものが勝つ。-x の形は
// フラグではなく位置引数（負の数を渡せるように）。-- 以降は、すべて位置引数。--help か -h があれば help が true。
// 知らないフラグと、値のないフラグは誤り。
func cliParseArgs(args []string, specs map[string]bool) (flags map[string]string, pos []string, help bool, err error) {
	flags = map[string]string{}
	for i := 0; i < len(args); i++ {
		a := args[i]
		if a == "--" {
			pos = append(pos, args[i+1:]...)
			break
		}
		if a == "--help" || a == "-h" {
			return nil, nil, true, nil
		}
		if !` + strings_ + `.HasPrefix(a, "--") {
			pos = append(pos, a)
			continue
		}
		name, value, hasValue := ` + strings_ + `.Cut(a[2:], "=")
		boolean, known := specs[name]
		if !known {
			return nil, nil, false, ` + fmt_ + `.Errorf("unknown flag --%s", name)
		}
		if !hasValue {
			if boolean {
				value = "true"
			} else {
				if i+1 >= len(args) {
					return nil, nil, false, ` + fmt_ + `.Errorf("flag --%s needs a value", name)
				}
				i++
				value = args[i]
			}
		}
		flags[name] = value
	}
	return flags, pos, false, nil
}

`)
	if f.usesLookup || f.usesLookupArg {
		b.WriteString(`// cliLookup は、フラグ flag の値、なければ環境変数 name の値（空でなければ）を返す。フラグが優先。
func cliLookup(flags map[string]string, flag string, env func(string) string, name string) (string, bool) {
	if flag != "" {
		if v, ok := flags[flag]; ok {
			return v, true
		}
	}
	if name != "" && env != nil {
		if v := env(name); v != "" {
			return v, true
		}
	}
	return "", false
}

`)
	}
	if f.usesLookupArg {
		b.WriteString(`// cliLookupArg は、i 番目の位置引数、なければ環境変数 name の値（空でなければ）を返す。
func cliLookupArg(pos []string, i int, env func(string) string, name string) (string, bool) {
	if i < len(pos) {
		return pos[i], true
	}
	return cliLookup(nil, "", env, name)
}

`)
	}
	b.WriteString(`// cliUsageError は、使い方の誤りを w（標準エラー）に出して 64 を返す。usage が空なら、使い方は出さない。
func cliUsageError(w ` + io + `.Writer, prog, usage, message string) int {
	` + fmt_ + `.Fprintf(w, "%s: %s\n", prog, message)
	if usage != "" {
		` + fmt_ + `.Fprint(w, "\n"+usage)
	}
	return 64
}

`)
	if f.usesValidation {
		errors, runtime := f.pkg("errors"), f.pkg(runtimePath)
		b.WriteString(`// cliValidationMessage は、Validate の誤りを「path: constraint; …」にする。
func cliValidationMessage(err error) string {
	var invalid *` + runtime + `.ValidationError
	if !` + errors + `.As(err, &invalid) {
		return err.Error()
	}
	parts := make([]string, len(invalid.Violations))
	for i, v := range invalid.Violations {
		parts[i] = v.String()
	}
	return ` + strings_ + `.Join(parts, "; ")
}

`)
	}
	if f.usesPtr {
		b.WriteString(`// cliPtr は v を指すポインタ（省略可能なフィールドの値）。
func cliPtr[T any](v T) *T { return &v }
`)
	}
	return b.String()
}

// commandUsage は、コマンドの使い方の、"usage: <prog>" に続く部分（docs/plugin-go-cli.md「使い方の表示」）: 一行目、
// コマンドの説明、位置引数、フラグ、環境変数だけのフィールドの順。
func commandUsage(c *command) string {
	var b strings.Builder
	b.WriteString(" " + c.name)
	var flags, envs, args []*field
	if c.input != nil {
		for _, f := range c.input.fields {
			switch {
			case f.arg:
				args = append(args, f)
			case f.flag != "":
				flags = append(flags, f)
			default:
				envs = append(envs, f)
			}
		}
	}
	if len(flags) > 0 {
		b.WriteString(" [flags]")
	}
	for _, f := range args {
		label := argLabel(f.name)
		switch {
		case f.array:
			b.WriteString(" [" + label + "...]")
		case f.required:
			b.WriteString(" " + label)
		default:
			b.WriteString(" [" + label + "]")
		}
	}
	b.WriteString("\n")
	if c.summary != "" {
		b.WriteString("\n" + c.summary + "\n")
	}
	section := func(title string, fields []*field, label func(*field) string) {
		if len(fields) == 0 {
			return
		}
		b.WriteString("\n" + title + ":\n")
		rows := make([][2]string, len(fields))
		for i, f := range fields {
			rows[i] = [2]string{label(f), fieldHelp(f)}
		}
		writeRows(&b, rows)
	}
	section("arguments", args, func(f *field) string {
		if f.array {
			return argLabel(f.name) + "..."
		}
		return argLabel(f.name)
	})
	section("flags", flags, func(f *field) string {
		if f.kind == kindBoolean {
			return "--" + f.flag
		}
		return "--" + f.flag + " <" + typeLabel(f) + ">"
	})
	section("environment", envs, func(f *field) string { return f.env })
	return b.String()
}

// typeLabel は、使い方に出す値の型: scalar ならその名前、核の型ならその名前。
func typeLabel(f *field) string {
	if r, ok := f.value.(ir.RefType); ok {
		return r.Target[strings.LastIndexByte(r.Target, '.')+1:]
	}
	return f.kind.label()
}

// fieldHelp は、フィールドの一行の説明: summary に、必須・既定値・代わりの環境変数の注記を足したもの。
func fieldHelp(f *field) string {
	s := f.summary
	var notes []string
	if f.required {
		notes = append(notes, "required")
	}
	if f.def != "" {
		notes = append(notes, "default: "+f.def)
	}
	if f.env != "" && (f.flag != "" || f.arg) {
		notes = append(notes, "env: "+f.env)
	}
	if len(notes) > 0 {
		if s != "" {
			s += " "
		}
		s += "(" + strings.Join(notes, ", ") + ")"
	}
	return s
}

// writeRows は「  <左>   <右>」の表を書く。左の幅をそろえる。右が空の行は、左だけ（行末に空白を残さない）。
func writeRows(b *strings.Builder, rows [][2]string) {
	width := 0
	for _, r := range rows {
		if len(r[0]) > width {
			width = len(r[0])
		}
	}
	for _, r := range rows {
		if r[1] == "" {
			b.WriteString("  " + r[0] + "\n")
			continue
		}
		b.WriteString("  " + r[0] + strings.Repeat(" ", width+3-len(r[0])) + r[1] + "\n")
	}
}

// argLabel は、位置引数の表示名（lowerCamelCase → UPPER_SNAKE。names → NAMES、dryRun → DRY_RUN）。
func argLabel(name string) string {
	var b strings.Builder
	for i, r := range name {
		if i > 0 && unicode.IsUpper(r) {
			b.WriteByte('_')
		}
		b.WriteRune(unicode.ToUpper(r))
	}
	return b.String()
}

package gocli

import (
	"fmt"
	"go/format"
	"strconv"
	"strings"
	"unicode"
)

// generate は program を cli/cli.go の中身にする。go/format で整形し、失敗すれば（生成器の不具合）その誤りと整形前の内容を返す。
func generate(p *program) ([]byte, error) {
	g := &generator{p: p}
	g.file()
	src, err := format.Source([]byte(g.b.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated code: %w\n%s", err, g.b.String())
	}
	return src, nil
}

type generator struct {
	p *program
	b strings.Builder
}

func (g *generator) w(format string, args ...any) {
	fmt.Fprintf(&g.b, format, args...)
}

func (g *generator) line(s string) { g.b.WriteString(s + "\n") }

// q は Go の文字列リテラル。
func q(s string) string { return strconv.Quote(s) }

func (g *generator) file() {
	p := g.p
	g.line("// Code generated by hozoc plugin go-cli; DO NOT EDIT.")
	g.line("")
	g.w("// Package cli は名前空間 %s のコマンドラインの骨組み（docs/plugin-go-cli.md）。\n", p.Namespace)
	g.line("//")
	g.line("// 人が書く main は、Ops の実装を組み立てて")
	g.line("//")
	g.line("//\tos.Exit(cli.Main(ops, cli.JSONPresenter{}, os.Args[1:], os.Getenv, os.Stdout, os.Stderr))")
	g.line("//")
	g.line("// を呼ぶだけ。")
	g.line("package cli")
	g.line("")
	g.b.WriteString(p.Imports.Render())
	g.line("")
	g.presenter()
	g.main()
	for _, c := range p.Commands {
		g.command(c)
	}
	g.helpers()
}

// presenter は Presenter / Failure / JSONPresenter（docs/plugin-go-cli.md「出力」「実行と表示」）。
func (g *generator) presenter() {
	g.line(`// Presenter は結果と例外の表示。既定は JSON（JSONPresenter）。
type Presenter interface {
	// Present は成功の結果を w に出す。void の op なら result は nil。
	Present(w io.Writer, command string, input any, result any) error
	// PresentError は例外を w に出す。
	PresentError(w io.Writer, command string, input any, f Failure) error
}

// Failure は例外の内容。Name は例外の FQN、Value は運ぶ値（なければ nil）で、
// 生成したコードが例外の型を型スイッチで見分けて入れる。Err は op が返した error そのもの（表示のメッセージに使える）。
// 宣言にない例外なら Name は空で Err だけ。
type Failure struct {
	Name  string
	Value any
	Err   error
}

// JSONPresenter は結果と例外を JSON で出す既定の Presenter。
type JSONPresenter struct{}

// Present は result を json.MarshalIndent で w に出す。nil なら何も出さない。
func (JSONPresenter) Present(w io.Writer, command string, input any, result any) error {
	if result == nil {
		return nil
	}
	b, err := json.MarshalIndent(result, "", "  ")
	if err != nil {
		return err
	}
	_, err = fmt.Fprintln(w, string(b))
	return err
}

// PresentError は Name があれば {"error": <Name>, "value": <Value>}（Value が nil なら value を省く）を、
// なければ {"error": <Err.Error()>} を w に出す。
func (JSONPresenter) PresentError(w io.Writer, command string, input any, f Failure) error {
	var body any
	switch {
	case f.Name != "" && f.Value != nil:
		body = struct {
			Error string ` + "`json:\"error\"`" + `
			Value any    ` + "`json:\"value\"`" + `
		}{f.Name, f.Value}
	case f.Name != "":
		body = struct {
			Error string ` + "`json:\"error\"`" + `
		}{f.Name}
	default:
		msg := "unknown error"
		if f.Err != nil {
			msg = f.Err.Error()
		}
		body = struct {
			Error string ` + "`json:\"error\"`" + `
		}{msg}
	}
	b, err := json.MarshalIndent(body, "", "  ")
	if err != nil {
		return err
	}
	_, err = fmt.Fprintln(w, string(b))
	return err
}
`)
}

// main は Main と全体の使い方。
func (g *generator) main() {
	p := g.p
	g.line("// Main は引数を解釈して ops の op を呼び、結果を p で表示し、終了コードを返す。")
	g.line("// args は os.Args[1:]（プログラム名を含まない）。env は環境変数の値を返す関数（os.Getenv。nil なら環境変数を見ない）。")
	g.line("// 終了コード: 成功 0、使い方の誤り 64、@cli.exitCode の付いた例外はその値、それ以外の例外と表示の失敗 70。")
	g.w("func Main(ops %s.Ops, p Presenter, args []string, env func(string) string, stdout, stderr io.Writer) int {\n", p.Package)
	g.line("\tprog := programName()")
	g.line("\tif len(args) == 0 {")
	g.line("\t\tfmt.Fprint(stderr, usage(prog))")
	g.line("\t\treturn 64")
	g.line("\t}")
	g.line("\tswitch args[0] {")
	g.line("\tcase \"help\", \"--help\", \"-h\":")
	g.line("\t\tfmt.Fprint(stdout, usage(prog))")
	g.line("\t\treturn 0")
	for _, c := range p.Commands {
		g.w("\tcase %s:\n", q(c.Name))
		g.w("\t\treturn run%s(ops, p, prog, args[1:], env, stdout, stderr)\n", c.Method)
	}
	g.line("\t}")
	g.line("\treturn usageError(stderr, prog, usage(prog), fmt.Sprintf(\"unknown command %q\", args[0]))")
	g.line("}")
	g.line("")

	width := 0
	for _, c := range p.Commands {
		if len(c.Name) > width {
			width = len(c.Name)
		}
	}
	var b strings.Builder
	b.WriteString("\ncommands:\n")
	for _, c := range p.Commands {
		b.WriteString("  " + pad(c.Name, width+3) + c.Summary + "\n")
	}
	g.line("// usage は全体の使い方（docs/plugin-go-cli.md「使い方の表示」）。")
	g.line("func usage(prog string) string {")
	g.w("\treturn \"usage: \" + prog + %s\n", q(" <command> [flags]\n"+b.String()))
	g.line("}")
	g.line("")
}

// command は一つのサブコマンドの run<Op>、fail<Op>、usage<Op>。
func (g *generator) command(c *command) {
	p := g.p
	m := c.Input
	us := "usage" + c.Method + "(prog)"

	g.w("// run%s はサブコマンド %s（%s）。\n", c.Method, c.Name, c.Op.Name)
	g.w("func run%s(ops %s.Ops, p Presenter, prog string, args []string, env func(string) string, stdout, stderr io.Writer) int {\n", c.Method, p.Package)

	// フラグの表。
	g.line("\tspecs := map[string]bool{")
	if m != nil {
		for _, f := range m.Fields {
			if f.Flag != "" {
				g.w("\t\t%s: %v,\n", q(f.Flag), f.Kind == kindBoolean)
			}
		}
	}
	g.line("\t}")
	g.line("\tflags, pos, help, err := parseArgs(args, specs)")
	g.line("\tif err != nil {")
	g.w("\t\treturn usageError(stderr, prog, %s, err.Error())\n", us)
	g.line("\t}")
	g.line("\tif help {")
	g.w("\t\tfmt.Fprint(stdout, %s)\n", us)
	g.line("\t\treturn 0")
	g.line("\t}")

	// 位置引数の数。
	nFixed := 0
	hasArray := false
	if m != nil {
		for _, f := range m.Args {
			if f.Array {
				hasArray = true
			} else {
				nFixed++
			}
		}
	}
	if !hasArray {
		g.w("\tif len(pos) > %d {\n", nFixed)
		g.w("\t\treturn usageError(stderr, prog, %s, fmt.Sprintf(\"too many arguments: %%d given, at most %d expected\", len(pos)))\n", us, nFixed)
		g.line("\t}")
	}

	input := "nil"
	if m != nil {
		input = "in"
		if m.HasDefault {
			g.w("\tin := %s.New%s()\n", p.Package, strings.TrimPrefix(m.GoType, p.Package+"."))
		} else {
			g.w("\tvar in %s\n", m.GoType)
		}
		if !m.hasFlags() {
			g.line("\t_ = flags")
		}
		argIndex := 0
		for _, f := range m.Fields {
			g.field(f, us, &argIndex)
		}
		g.line("\tif err := in.Validate(); err != nil {")
		g.line("\t\treturn usageError(stderr, prog, \"\", \"invalid input: \"+validationMessage(err))")
		g.line("\t}")
	} else {
		g.line("\t_, _ = flags, env")
	}

	// 実行と表示。
	call := fmt.Sprintf("ops.%s(context.Background()", c.Method)
	if m != nil {
		call += ", in"
	}
	call += ")"
	if c.Void {
		g.w("\terr = %s\n", call)
		g.line("\tif err != nil {")
		g.w("\t\treturn fail%s(p, prog, %s, err, stderr)\n", c.Method, input)
		g.line("\t}")
		g.w("\tif err := p.Present(stdout, %s, %s, nil); err != nil {\n", q(c.Name), input)
	} else {
		g.w("\tresult, err := %s\n", call)
		g.line("\tif err != nil {")
		g.w("\t\treturn fail%s(p, prog, %s, err, stderr)\n", c.Method, input)
		g.line("\t}")
		g.w("\tif err := p.Present(stdout, %s, %s, result); err != nil {\n", q(c.Name), input)
	}
	g.line("\t\tfmt.Fprintf(stderr, \"%s: %v\\n\", prog, err)")
	g.line("\t\treturn 70")
	g.line("\t}")
	g.line("\treturn 0")
	g.line("}")
	g.line("")

	// 例外の見分け。
	g.w("// fail%s は %s の例外を Signature の順に見分けて Failure を作り、終了コードを決めて p で表示する。\n", c.Method, c.Name)
	g.w("func fail%s(p Presenter, prog string, input any, err error, stderr io.Writer) int {\n", c.Method)
	g.line("\tf, code := Failure{Err: err}, 70")
	for i, e := range c.Exceptions {
		prefix := "\t"
		if i > 0 {
			prefix = " else "
		}
		if e.HasValue {
			g.w("%sif e, ok := asException[%s](err); ok {\n", prefix, e.GoType)
			g.w("\t\tf, code = Failure{Name: %s, Value: e.Value, Err: err}, %d\n", q(e.FQN), e.ExitCode)
		} else {
			g.w("%sif _, ok := asException[%s](err); ok {\n", prefix, e.GoType)
			g.w("\t\tf, code = Failure{Name: %s, Err: err}, %d\n", q(e.FQN), e.ExitCode)
		}
		g.b.WriteString("\t}")
	}
	if len(c.Exceptions) > 0 {
		g.line("")
	}
	g.w("\tif err := p.PresentError(stderr, %s, input, f); err != nil {\n", q(c.Name))
	g.line("\t\tfmt.Fprintf(stderr, \"%s: %v\\n\", prog, err)")
	g.line("\t\treturn 70")
	g.line("\t}")
	g.line("\treturn code")
	g.line("}")
	g.line("")

	// 使い方。
	g.w("// usage%s は %s の使い方。\n", c.Method, c.Name)
	g.w("func usage%s(prog string) string {\n", c.Method)
	g.w("\treturn \"usage: \" + prog + %s\n", q(commandUsage(c)))
	g.line("}")
	g.line("")
}

// field は一つのフィールドの値の取り出しと変換。
func (g *generator) field(f *field, us string, argIndex *int) {
	target := "in." + f.GoName
	assign := func(expr string) string {
		if f.Optional {
			return target + " = ptr(" + expr + ")"
		}
		return target + " = " + expr
	}
	var label, what string // 誤りのメッセージで値の出どころを指す言葉
	switch {
	case f.Arg:
		label = argLabel(f.Name)
		what = "argument " + label
	case f.Flag != "":
		label = "--" + f.Flag
		what = "flag " + label
	default:
		label = f.Env
		what = "environment variable " + label
	}

	if f.Array {
		g.w("\tif len(pos) > %d {\n", *argIndex)
		rest := "pos"
		if *argIndex > 0 {
			rest = fmt.Sprintf("pos[%d:]", *argIndex)
		}
		if f.ConvType == "string" {
			g.w("\t\t%s = %s\n", target, rest)
		} else {
			g.w("\t\tfor _, v := range %s {\n", rest)
			g.w("\t\t\t%s = append(%s, %s(v))\n", target, target, f.ConvType)
			g.line("\t\t}")
		}
		g.line("\t}")
		return
	}

	// 値の取り出し。
	if f.Arg {
		if f.Env != "" {
			g.w("\tif v, ok := lookupArg(pos, %d, env, %s); ok {\n", *argIndex, q(f.Env))
		} else {
			g.w("\tif v, ok := lookupArg(pos, %d, nil, \"\"); ok {\n", *argIndex)
		}
		*argIndex++
	} else {
		g.w("\tif v, ok := lookup(flags, %s, env, %s); ok {\n", q(f.Flag), q(f.Env))
	}
	// 変換。
	switch f.Kind {
	case kindString:
		if f.ConvType == "string" {
			g.w("\t\t%s\n", assign("v"))
		} else {
			g.w("\t\t%s\n", assign(f.ConvType+"(v)"))
		}
	case kindBoolean:
		g.line("\t\tb, err := strconv.ParseBool(v)")
		g.line("\t\tif err != nil {")
		g.w("\t\t\treturn usageError(stderr, prog, %s, fmt.Sprintf(\"invalid value %%q for %s: want boolean\", v))\n", us, label)
		g.line("\t\t}")
		g.w("\t\t%s\n", assign(convert(f.ConvType, "bool", "b")))
	case kindInt:
		g.line("\t\tn, err := strconv.ParseInt(v, 10, 64)")
		g.line("\t\tif err != nil {")
		g.w("\t\t\treturn usageError(stderr, prog, %s, fmt.Sprintf(\"invalid value %%q for %s: want int\", v))\n", us, label)
		g.line("\t\t}")
		g.w("\t\t%s\n", assign(convert(f.ConvType, "int64", "n")))
	case kindFloat:
		g.line("\t\tx, err := strconv.ParseFloat(v, 64)")
		g.line("\t\tif err != nil {")
		g.w("\t\t\treturn usageError(stderr, prog, %s, fmt.Sprintf(\"invalid value %%q for %s: want float\", v))\n", us, label)
		g.line("\t\t}")
		g.w("\t\t%s\n", assign(convert(f.ConvType, "float64", "x")))
	}
	if f.Required {
		g.line("\t} else {")
		g.w("\t\treturn usageError(stderr, prog, %s, \"missing required %s\")\n", us, what)
	}
	g.line("\t}")
}

// convert は値 v（Go の型 from）を型 to にする式。同じ型ならそのまま。
func convert(to, from, v string) string {
	if to == from {
		return v
	}
	return to + "(" + v + ")"
}

// helpers は生成するファイルに常に置く補助の関数。
func (g *generator) helpers() {
	g.w("// programName は使い方に出すプログラム名（filepath.Base(os.Args[0])）。\n")
	g.line("func programName() string {")
	g.line("\tif len(os.Args) > 0 && os.Args[0] != \"\" {")
	g.line("\t\treturn filepath.Base(os.Args[0])")
	g.line("\t}")
	g.w("\treturn %s\n", q(lastSegment(g.p.Namespace)))
	g.line("}")
	g.line("")
	g.line(`// parseArgs は args をフラグと位置引数に分ける（docs/plugin-go-cli.md「引数の解釈」）。
// specs はフラグ名 → boolean か。フラグは --name value か --name=value で、boolean は --name だけで true
// （--name=false は取れる）。-- 以降はすべて位置引数。--help か -h があれば help が true。
// 知らないフラグ、値のないフラグは誤り。
func parseArgs(args []string, specs map[string]bool) (flags map[string]string, pos []string, help bool, err error) {
	flags = map[string]string{}
	for i := 0; i < len(args); i++ {
		a := args[i]
		if a == "--" {
			pos = append(pos, args[i+1:]...)
			break
		}
		if a == "--help" || a == "-h" {
			return nil, nil, true, nil
		}
		if !strings.HasPrefix(a, "--") {
			pos = append(pos, a)
			continue
		}
		name, value, hasValue := strings.Cut(a[2:], "=")
		boolean, known := specs[name]
		if !known {
			return nil, nil, false, fmt.Errorf("unknown flag --%s", name)
		}
		if !hasValue {
			if boolean {
				value = "true"
			} else {
				if i+1 >= len(args) {
					return nil, nil, false, fmt.Errorf("flag --%s needs a value", name)
				}
				i++
				value = args[i]
			}
		}
		flags[name] = value
	}
	return flags, pos, false, nil
}

// lookup はフラグの値、なければ環境変数 name の値（空でなければ）を返す。フラグが優先。
func lookup(flags map[string]string, flag string, env func(string) string, name string) (string, bool) {
	if flag != "" {
		if v, ok := flags[flag]; ok {
			return v, true
		}
	}
	if name != "" && env != nil {
		if v := env(name); v != "" {
			return v, true
		}
	}
	return "", false
}

// lookupArg は i 番目の位置引数、なければ環境変数 name の値（空でなければ）を返す。
func lookupArg(pos []string, i int, env func(string) string, name string) (string, bool) {
	if i < len(pos) {
		return pos[i], true
	}
	return lookup(nil, "", env, name)
}

// usageError は使い方の誤りを標準エラーに出して 64 を返す。usage が空なら使い方は出さない。
func usageError(stderr io.Writer, prog, usage, msg string) int {
	fmt.Fprintf(stderr, "%s: %s\n", prog, msg)
	if usage != "" {
		fmt.Fprint(stderr, "\n"+usage)
	}
	return 64
}

// validationMessage は Validate の誤りを「path: constraint; ...」にする（docs/plugin-go-cli.md「引数の解釈」）。
func validationMessage(err error) string {
	var ve *runtime.ValidationError
	if !errors.As(err, &ve) {
		return err.Error()
	}
	parts := make([]string, len(ve.Violations))
	for i, v := range ve.Violations {
		parts[i] = v.String()
	}
	return strings.Join(parts, "; ")
}

// asException は err の連鎖の中の例外 T を取り出す。値でも *T でも見つける（P は *T。型推論で埋まる）。
func asException[T error, P interface {
	*T
	error
}](err error) (T, bool) {
	var v T
	if errors.As(err, &v) {
		return v, true
	}
	var p P
	if errors.As(err, &p) && p != nil {
		return *p, true
	}
	return v, false
}

// ptr は v を指すポインタ（optional のフィールドのため）。
func ptr[T any](v T) *T { return &v }
`)
}

// commandUsage はコマンドの使い方の、"usage: <prog>" に続く部分。
func commandUsage(c *command) string {
	var b strings.Builder
	b.WriteString(" " + c.Name)
	m := c.Input
	var flags, envs, args []*field
	if m != nil {
		for _, f := range m.Fields {
			switch {
			case f.Arg:
				args = append(args, f)
			case f.Flag != "":
				flags = append(flags, f)
			default:
				envs = append(envs, f)
			}
		}
	}
	if len(flags) > 0 {
		b.WriteString(" [flags]")
	}
	for _, f := range args {
		label := argLabel(f.Name)
		switch {
		case f.Array:
			b.WriteString(" [" + label + "...]")
		case f.Required:
			b.WriteString(" " + label)
		default:
			b.WriteString(" [" + label + "]")
		}
	}
	b.WriteString("\n")
	if c.Summary != "" {
		b.WriteString("\n" + c.Summary + "\n")
	}
	if len(args) > 0 {
		b.WriteString("\narguments:\n")
		rows := make([][2]string, len(args))
		for i, f := range args {
			label := argLabel(f.Name)
			if f.Array {
				label += "..."
			}
			rows[i] = [2]string{label, fieldHelp(f)}
		}
		writeRows(&b, rows)
	}
	if len(flags) > 0 {
		b.WriteString("\nflags:\n")
		rows := make([][2]string, len(flags))
		for i, f := range flags {
			label := "--" + f.Flag
			if f.Kind != kindBoolean {
				label += " <" + f.TypeLabel + ">"
			}
			rows[i] = [2]string{label, fieldHelp(f)}
		}
		writeRows(&b, rows)
	}
	if len(envs) > 0 {
		b.WriteString("\nenvironment:\n")
		rows := make([][2]string, len(envs))
		for i, f := range envs {
			rows[i] = [2]string{f.Env, fieldHelp(f)}
		}
		writeRows(&b, rows)
	}
	return b.String()
}

// fieldHelp はフィールドの一行の説明: summary に必須・既定値・環境変数の注記を足したもの。
func fieldHelp(f *field) string {
	s := f.Summary
	var notes []string
	if f.Required {
		notes = append(notes, "required")
	}
	if f.Default != "" {
		notes = append(notes, "default: "+f.Default)
	}
	if f.Env != "" && (f.Flag != "" || f.Arg) {
		notes = append(notes, "env: "+f.Env)
	}
	if len(notes) > 0 {
		if s != "" {
			s += " "
		}
		s += "(" + strings.Join(notes, ", ") + ")"
	}
	return s
}

// writeRows は「  <左>   <右>」の表を書く。左の幅を揃える。
func writeRows(b *strings.Builder, rows [][2]string) {
	width := 0
	for _, r := range rows {
		if len(r[0]) > width {
			width = len(r[0])
		}
	}
	for _, r := range rows {
		b.WriteString("  " + pad(r[0], width+3) + r[1] + "\n")
	}
}

// pad は s を幅 width まで空白で埋める。
func pad(s string, width int) string {
	if len(s) >= width {
		return s
	}
	return s + strings.Repeat(" ", width-len(s))
}

// argLabel は位置引数の表示名（lowerCamelCase → UPPER_SNAKE。namespaces → NAMESPACES、dryRun → DRY_RUN）。
func argLabel(name string) string {
	var b strings.Builder
	for i, r := range name {
		if i > 0 && unicode.IsUpper(r) {
			b.WriteByte('_')
		}
		b.WriteRune(unicode.ToUpper(r))
	}
	return b.String()
}

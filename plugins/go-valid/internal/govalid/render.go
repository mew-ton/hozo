// このファイルは validate.go のテキスト（docs/plugin-go-valid.md「出力」「scalar」「model」）。検査（emit.go）を通った入力だけを描く。

// runtimePath は、生成したコードが import する runtime パッケージ（docs/plugin-go-valid.md「runtime」）。
const runtimePath = "github.com/mew-ton/hozo/runtime"

// 生成したコードの、パッケージに足す非公開の名前（前置きは valid。docs/plugin-go.md「相乗りのファイル」）。
const (
	helperAppend  = "validAppend"
	helperKeys    = "validKeys"
	patternPrefix = "validPattern"
)

// file は、描いている途中の validate.go。
type file struct {
	g  *generator
	im *golang.Imports
	// reserved は、このファイルが import するパッケージの名前（一度目に描いて決めたもの）。局所の名前が避ける。
	reserved map[string]bool
	// patterns は pattern の正規表現の変数（宣言順）。taken は、その名前。
	patterns []string
	taken    map[string]bool
	// usesAppend、usesKeys は、補助の関数を使ったか（使うときだけ、ファイルの末尾に出す）。
	usesAppend, usesKeys bool
}

// runtime は、runtime パッケージを修飾する名前。使うときに import に足す。
func (f *file) runtime() string { return f.im.Add(runtimePath, "runtime") }

// local は、メソッドの中の局所の名前。このファイルが import するパッケージの名前と当たれば、当たらなくなるまで末尾に _ を足す。
func (f *file) local(name string) string {
	for f.reserved[name] {
		name += "_"
	}
	return name
}

// render は validate.go の全体を作り、go/format で整形する。import の名前を文書の決まりの順で決めるために、二度描く
// （docs/plugin-go.md「パッケージと import パス」の「import の名前」。基底と同じ手順）。
func (g *generator) render(targets []target) (string, error) {
	first := &file{g: g, im: golang.NewImports(g.view, g.layout, g.root, true)}
	first.draw(targets)
	second := &file{g: g, im: first.im.Canonical(), reserved: map[string]bool{}}
	for _, name := range second.im.Names() {
		second.reserved[name] = true
	}
	text := second.draw(targets)
	if err := second.im.Err(); err != nil {
		return "", fmt.Errorf("%s: %w（CFG-22 が通したはずのもの）", FileName, err)
	}
	src, err := format.Source([]byte(text))
	if err != nil {
		return "", fmt.Errorf("生成した %s を整形できない（生成器の不具合）: %w\n%s", FileName, err, text)
	}
	return string(src), nil
}

// draw は、ファイルのテキスト（整形前）を作る: ヘッダ、package 節、import、pattern の変数、メソッド（宣言順）、補助の関数。
func (f *file) draw(targets []target) string {
	f.taken = map[string]bool{}
	var methods strings.Builder
	for _, t := range targets {
		switch {
		case t.scalar != nil:
			methods.WriteString(f.scalar(t.scalar))
		case t.model != nil:
			methods.WriteString(f.model(t.model))
		default:
			methods.WriteString(f.wrapper(t.union, t.arm))
		}
	}
	var helpers strings.Builder
	if f.usesAppend {
		helpers.WriteString(f.appendHelper())
	}
	if f.usesKeys {
		helpers.WriteString(f.keysHelper())
	}
	var b strings.Builder
	b.WriteString("// Code generated by hozoc " + TranspilerName + " " + plugin.Version + "; DO NOT EDIT.\n\n")
	b.WriteString("package " + f.g.layout.DefName + "\n\n")
	b.WriteString(f.im.Render())
	b.WriteString("\n")
	for _, p := range f.patterns {
		b.WriteString(p)
	}
	if len(f.patterns) > 0 {
		b.WriteString("\n")
	}
	b.WriteString(methods.String())
	b.WriteString(helpers.String())
	return b.String()
}

// typeName は、N の宣言 fqn の Go の型の名前（定義のパッケージの中なので、修飾なし）。
func (f *file) typeName(fqn string) string { return golang.TypeName(fqn, f.g.declNS[fqn]) }

// pattern は、制約 c（pattern）の正規表現のパッケージの変数を足し、その名前を返す。owner は、付いた先の名前
// （型名か、model の名前とフィールド名を先頭大文字にしたもの）。名前が当たれば、後ろの方に 2、3、… を付ける。
func (f *file) pattern(c constraint, owner string) string {
	name := patternPrefix + owner
	for i := 2; f.taken[name]; i++ {
		name = patternPrefix + owner + strconv.Itoa(i)
	}
	f.taken[name] = true
	f.patterns = append(f.patterns, fmt.Sprintf("var %s = %s.MustCompile(%s)\n", name, f.im.Add("regexp", "regexp"), strconv.Quote(c.regex)))
	return name
}

// open は、メソッドの頭: コメントと、レシーバと、違反を集める変数。
func (f *file) open(comment, receiver, typeName, violations string) string {
	return fmt.Sprintf("// %s\nfunc (%s %s) %s() error {\nvar %s []%s.Violation\n", comment, receiver, typeName, method, violations, f.runtime())
}

// close は、メソッドの終わり: 違反がなければ nil、あれば *runtime.ValidationError。
func (f *file) close(violations string) string {
	return fmt.Sprintf("if len(%s) == 0 {\nreturn nil\n}\nreturn &%s.ValidationError{Violations: %s}\n}\n\n", violations, f.runtime(), violations)
}

// scalar は、scalar s の Validate（docs/plugin-go-valid.md「scalar」）: 元の scalar が Validate を持つなら、まずそれ。
// 次に、自分に付いた制約を、書かれた順に。Path は ""。
func (f *file) scalar(s *ir.Scalar) string {
	name := f.typeName(s.Name)
	v, violations := f.local("v"), f.local("violations")
	var b strings.Builder
	b.WriteString(f.open(fmt.Sprintf("%s は %s の制約を確かめる。違反がなければ nil。", method, s.Name), v, name, violations))
	if _, ok := f.g.validatedRef(s.Base); ok {
		f.usesAppend = true
		fmt.Fprintf(&b, "%s = %s(%s, \"\", %s(%s).%s())\n", violations, helperAppend, violations, golang.GoType(s.Base, f.im), v, method)
	}
	core, ok := f.g.coreOf(s.Base)
	for i := range s.Decorators {
		app := &s.Decorators[i]
		if !f.g.vocab[app.Decorator] {
			continue
		}
		c, _ := parse(app, core, ok, "")
		if c.decorator == validPattern {
			c.variable = f.pattern(c, name)
		}
		b.WriteString(f.violation(c, v, `""`, violations))
	}
	b.WriteString(f.close(violations))
	return b.String()
}

// wrapper は、union u のアーム a を包む型の Validate（docs/plugin-go-valid.md「出力」）: 中身の Validate を、そのまま返す。
func (f *file) wrapper(u *ir.Union, a *ir.UnionArm) string {
	v := f.local("v")
	return fmt.Sprintf("// %s は union %s のアーム %s（%s）の制約を確かめる。違反がなければ nil。\nfunc (%s %s) %s() error {\nreturn %s.Value.%s()\n}\n\n",
		method, u.Name, a.Name, golang.TypeDisplay(a.Type), v, f.typeName(u.Name)+golang.Capitalize(a.Name), method, v, method)
}

// violation は、制約 c 一つの検査: 値 value が違反していれば、Path が path（Go の式）の違反を足す。
func (f *file) violation(c constraint, value, path, violations string) string {
	return fmt.Sprintf("if %s {\n%s = append(%s, %s.Violation{Path: %s, Constraint: %s})\n}\n",
		c.condition(value, f), violations, violations, f.runtime(), path, strconv.Quote(c.name))
}

// model は、model m の Validate（docs/plugin-go-valid.md「model」）: フィールドの順に、フィールドの型の Validate と、
// フィールドに付いた制約。どちらもないフィールドは飛ばす。
func (f *file) model(m *ir.Model) string {
	name := f.typeName(m.Name)
	recv, violations := f.local("m"), f.local("violations")
	var b strings.Builder
	b.WriteString(f.open(fmt.Sprintf("%s は %s の各フィールドの制約を確かめる。違反の Path はフィールド名を . でつないだもの。", method, m.Name), recv, name, violations))
	for i := range m.Fields {
		fd := &m.Fields[i]
		cons, _ := f.g.fieldConstraints(fd, "")
		for j := range cons {
			if cons[j].decorator == validPattern {
				cons[j].variable = f.pattern(cons[j], name+golang.Capitalize(fd.Name))
			}
		}
		b.WriteString(f.value(recv+"."+golang.FieldName(fd.Name), pathExpr{{text: fd.Name, literal: true}}, fd.Type, cons, 0, violations))
	}
	b.WriteString(f.close(violations))
	return b.String()
}

// value は、値一つの検査（docs/plugin-go-valid.md「model」の 1 と 2、包まれた型の表）: expr はその値の Go の式、path は違反の
// Path、t は型、cons は、その値に付いた制約（フィールドそのものの値だけが持つ）。depth は、配列とインデックスの model の入れ子の深さ
// （i0、x0、k0 の番号）。violations は、違反を集める変数の名前。確かめるものがなければ ""。
func (f *file) value(expr string, path pathExpr, t ir.Type, cons []constraint, depth int, violations string) string {
	switch x := t.(type) {
	case ir.CaseType:
		return f.value(expr, path, x.Of, cons, depth, violations)
	case ir.OptionalType:
		if golang.IsNillable(x.Of, f.g.p) {
			// Go でポインタにならない（array、インデックスの model の nil が「なし」）: そのまま回す
			return f.value(expr, path, x.Of, cons, depth, violations)
		}
		inner := f.value("*"+expr, path, x.Of, cons, depth, violations)
		if inner == "" {
			return ""
		}
		return fmt.Sprintf("if %s != nil {\n%s}\n", expr, inner)
	case ir.ArrayType:
		// 要素（1）の後に、配列のフィールドに付いた length（2。要素の数に掛かる）
		var b strings.Builder
		if f.g.checked(f.g.through(x.Of)) {
			i, elem := "i"+strconv.Itoa(depth), "x"+strconv.Itoa(depth)
			index := part{text: f.im.Add("strconv", "strconv") + ".Itoa(" + i + ")"}
			inner := f.value(elem, path.index(index), x.Of, nil, depth+1, violations)
			fmt.Fprintf(&b, "for %s, %s := range %s {\n%s}\n", i, elem, expr, inner)
		}
		for _, c := range cons {
			b.WriteString(f.violation(c, expr, path.render(), violations))
		}
		return b.String()
	case ir.RefType:
		// インデックスの model: キーの辞書順に、値を回す（docs/plugin-go-valid.md「model」の表）
		if idx := f.g.p.IndexOf(x); idx != nil {
			if !f.g.checked(f.g.through(idx.Value)) {
				return ""
			}
			f.usesKeys = true
			k, elem := "k"+strconv.Itoa(depth), "x"+strconv.Itoa(depth)
			inner := f.value(elem, path.index(part{text: "string(" + k + ")"}), idx.Value, nil, depth+1, violations)
			return fmt.Sprintf("for _, %s := range %s(%s) {\n%s := %s[%s]\n%s}\n", k, helperKeys, expr, elem, expr, k, inner)
		}
	}
	var b strings.Builder
	if f.g.unionValidated(t) {
		// 値が当たっているアームの値が、Validate を持てば、呼ぶ（docs/plugin-go-valid.md「model」の表の union の行）
		f.usesAppend = true
		u := f.local("u" + strconv.Itoa(depth))
		fmt.Fprintf(&b, "if %s, ok := %s.(interface{ %s() error }); ok {\n%s = %s(%s, %s, %s.%s())\n}\n", u, expr, method, violations, helperAppend, violations, path.render(), u, method)
	}
	if _, ok := f.g.validatedRef(t); ok {
		f.usesAppend = true
		recv := expr
		if strings.HasPrefix(recv, "*") {
			recv = "(" + recv + ")"
		}
		fmt.Fprintf(&b, "%s = %s(%s, %s, %s.%s())\n", violations, helperAppend, violations, path.render(), recv, method)
	}
	for _, c := range cons {
		b.WriteString(f.violation(c, expr, path.render(), violations))
	}
	return b.String()
}

// part は Path の式の部分一つ: 文字列のリテラルか、文字列の Go の式。
type part struct {
	text    string
	literal bool
}

// pathExpr は、違反の Path の Go の式（部分を + でつないだもの）。
type pathExpr []part

// index は、p の後ろに `[<式>]` を足した式（配列の添字、インデックスの model のキー）。
func (p pathExpr) index(expr part) pathExpr {
	out := append(pathExpr{}, p...)
	return append(out, part{text: "[", literal: true}, expr, part{text: "]", literal: true})
}

// render は Go の式にする。隣り合うリテラルは、一つにまとめる。
func (p pathExpr) render() string {
	var parts []string
	lit, open := "", false
	flush := func() {
		if open {
			parts = append(parts, strconv.Quote(lit))
			lit, open = "", false
		}
	}
	for _, x := range p {
		if x.literal {
			lit, open = lit+x.text, true
			continue
		}
		flush()
		parts = append(parts, x.text)
	}
	flush()
	if len(parts) == 0 {
		return `""`
	}
	return strings.Join(parts, " + ")
}

// appendHelper は、補助の関数 validAppend（docs/plugin-go-valid.md「runtime」）。
func (f *file) appendHelper() string {
	rt, errs := f.runtime(), f.im.Add("errors", "errors")
	return fmt.Sprintf(`// %[1]s は err が *%[2]s.ValidationError なら、その違反の Path に path を前置して dst に足す。
func %[1]s(dst []%[2]s.Violation, path string, err error) []%[2]s.Violation {
	if err == nil {
		return dst
	}
	var ve *%[2]s.ValidationError
	if !%[3]s.As(err, &ve) {
		return append(dst, %[2]s.Violation{Path: path, Constraint: err.Error()})
	}
	for _, x := range ve.Violations {
		p := path
		if x.Path != "" {
			p = path + "." + x.Path
		}
		dst = append(dst, %[2]s.Violation{Path: p, Constraint: x.Constraint})
	}
	return dst
}

`, helperAppend, rt, errs)
}

// keysHelper は、補助の関数 validKeys: インデックスの model のキーを辞書順に並べる（docs/plugin-go-valid.md「model」の表）。
func (f *file) keysHelper() string {
	return fmt.Sprintf(`// %[1]s は m のキーを、辞書順に並べて返す。
func %[1]s[K ~string, V any](m map[K]V) []K {
	keys := make([]K, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	%[2]s.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
	return keys
}

`, helperKeys, f.im.Add("sort", "sort"))
}

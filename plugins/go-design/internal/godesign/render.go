// このファイルは、テストのパッケージの design.go（plugins/go-design/spec/go-design.hozo の Requirement.Output、Requirement.FlowPort、Requirement.RequirementPort）を
// 描く。検査（emit.go）を通った入力だけを描く。期待する出力の実物は、サンプル tests/samples/shop-server/ の
// gen/flows/flowstest/design.go。
//
// フローごと、要求ごとに出す行は、宣言（op の名前、引数、戻り値の型、説明。ケースの名前、説明。@prd.ref の引数）だけから作る
// （docs/requirements.md「出力を推論しない」）。型で、形を変えるのは、フローが値を返すかどうかだけ。

// bodyNames は、design.go の関数の本体が、決まった名前で使う識別子（plugins/go-design/spec/go-design.hozo の Requirement.Output）。import の名前に使わない。
var bodyNames = []string{"t", "c", "k", "ops", "ctx", "got", "err"}

// stdPackages は、design.go が、決まった名前で書く、標準ライブラリのパッケージ（import パス → 名前）。
var stdPackages = map[string]string{"context": "context", "testing": "testing"}

// file は、描いている途中の design.go。
type file struct {
	g  *generator
	im *golang.Imports
	// renamed は、決まった名前で書くパッケージ（stdPackages）が、別の名前で import されたもの（あれば、生成器の不具合）。
	renamed []string
}

// use は、決まった名前で書くパッケージ path を import に足し、その名前を返す。
func (f *file) use(path string) string {
	want := stdPackages[path]
	if got := f.im.Add(path, want); got != want {
		f.renamed = append(f.renamed, fmt.Sprintf("%s が %s になった", path, got))
	}
	return want
}

// render は、design.go の全体を作り、go/format で整形する。import の名前を文書の決まりの順で決めるために、二度描く
// （plugins/go/spec/go.hozo の Requirement.Layout の「パッケージと import パス」の「import の名前」。基底と同じ手順）。
func (g *generator) render(flows []flow, classes []class) (string, error) {
	where := g.layout.TestName + "/" + FileName
	im := golang.NewTestImports(g.view, g.layout)
	im.Reserve(bodyNames...)
	first := &file{g: g, im: im}
	first.draw(flows, classes)
	second := &file{g: g, im: first.im.Canonical()}
	text := second.draw(flows, classes)
	if err := second.im.Err(); err != nil {
		return "", fmt.Errorf("%s: %w（CFG-22 が通したはずのもの）", where, err)
	}
	if len(second.renamed) > 0 {
		return "", fmt.Errorf("%s: 決まった名前で書くパッケージの import の名前が変わった（生成器の不具合）: %s", where, strings.Join(second.renamed, "、"))
	}
	src, err := format.Source([]byte(text))
	if err != nil {
		return "", fmt.Errorf("生成した %s を整形できない（生成器の不具合）: %w\n%s", where, err, text)
	}
	return string(src), nil
}

// draw は、ファイルのテキスト（整形前）を作る: ヘッダ、package 節、import、フローごとのケース、まとめ、走らせる関数、
// 要求ごとの入れ物、走らせる関数。
func (f *file) draw(flows []flow, classes []class) string {
	var body strings.Builder
	if len(flows) > 0 {
		for i := range flows {
			body.WriteString(f.flowCase(&flows[i]))
		}
		body.WriteString(f.flowCases(flows))
		body.WriteString(f.runFlows(flows))
	}
	if len(classes) > 0 {
		body.WriteString(f.requirements(classes))
		body.WriteString(f.runRequirements(classes))
	}
	var b strings.Builder
	b.WriteString("// Code generated by hozoc " + TranspilerName + " " + plugin.Version + "; DO NOT EDIT.\n\n")
	b.WriteString("package " + f.g.layout.TestName + "\n\n")
	b.WriteString(f.im.Render())
	b.WriteString("\n")
	b.WriteString(strings.TrimSuffix(body.String(), "\n"))
	return b.String()
}

// docLines は、説明 doc の全文を、行ごとに分ける。説明がなければ nil。
func docLines(doc *ir.Doc) []string {
	if doc == nil || doc.Body == "" {
		return nil
	}
	return strings.Split(doc.Body, "\n")
}

// continued は、説明の二行目から先を、行ごとに `// ` を付けて続ける（空の行は `//`）。
func continued(b *strings.Builder, lines []string) {
	for _, line := range lines {
		if line == "" {
			b.WriteString("//\n")
		} else {
			b.WriteString("// " + line + "\n")
		}
	}
}

// flowCase は、フロー一つのケースの型 <Op>FlowCase（plugins/go-design/spec/go-design.hozo の Requirement.FlowPort）: フローの引数、Given、Then。
func (f *file) flowCase(fl *flow) string {
	name := fl.method() + flowCaseSuffix
	var b strings.Builder
	fmt.Fprintf(&b, "// %s は、フロー %s の、E2E テストのケース: フローの引数と、今の状態の用意と、足りない確かめ。\n", name, fl.op.Name)
	if lines := docLines(fl.op.Description); len(lines) > 0 {
		b.WriteString("// フロー: " + lines[0] + "\n")
		continued(&b, lines[1:])
	}
	fmt.Fprintf(&b, "type %s struct {\n", name)
	fields := fl.fields()
	for i, p := range fl.op.Params {
		fmt.Fprintf(&b, "%s %s\n", fields[i], golang.GoType(p.Type, f.im))
	}
	fmt.Fprintf(&b, "// Given は、フローを呼ぶ前に、今の状態を用意する（nil なら、呼ばない）。\nGiven func(ctx %s.Context) error\n", f.use("context"))
	if fl.hasValue() {
		fmt.Fprintf(&b, "// Then は、フローが、正常に終わったと確かめた後に、呼ばれる（nil なら、呼ばない）。got は、フローが返した値。後の状態は、ここで確かめる。\n"+
			"Then func(t *%s.T, got %s)\n", f.use("testing"), golang.GoType(fl.op.Returns, f.im))
	} else {
		fmt.Fprintf(&b, "// Then は、フローが、正常に終わったと確かめた後に、呼ばれる（nil なら、呼ばない）。後の状態は、ここで確かめる。\n"+
			"Then func(t *%s.T)\n", f.use("testing"))
	}
	b.WriteString("}\n\n")
	return b.String()
}

// flowCases は、フローのケースのまとめ FlowCases: フローごとに、メソッド一つ（宣言順）。
func (f *file) flowCases(flows []flow) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s は、@%s の付いた op の、E2E テストのケース。フローごとに、メソッド一つ（宣言順）。\n"+
		"// メソッドが一つでも足りない値は、%s に渡すところでコンパイルできない。\ntype %s interface {\n", flowCasesName, businessFlow, runFlowsName, flowCasesName)
	for i := range flows {
		m := flows[i].method()
		fmt.Fprintf(&b, "%s() %s%s\n", m, m, flowCaseSuffix)
	}
	b.WriteString("}\n\n")
	return b.String()
}

// runFlows は、走らせる関数 RunFlows（同）: フローごとに、t.Run を一つ。Given、フロー、正常に終わったことの確かめ、
// Then の順。行の形は、フローが値を返すかどうかだけで決まる。
func (f *file) runFlows(flows []flow) string {
	testing, context := f.use("testing"), f.use("context")
	var b strings.Builder
	fmt.Fprintf(&b, "// %s は、フローごとに、テストを一つ走らせる。テストの名前は、フローの FQN。\n"+
		"// Given を呼んでから、ops のフロー（配線は、基底が作る）を呼び、正常に終わったことを確かめてから、Then を呼ぶ。\n"+
		"func %s(t *%s.T, ops %sOps, c %s) {\n", runFlowsName, runFlowsName, testing, f.im.Qualifier(f.g.view.Viewer), flowCasesName)
	for i := range flows {
		fl := &flows[i]
		m := fl.method()
		fmt.Fprintf(&b, "t.Run(%s, func(t *%s.T) {\nk := c.%s()\nctx := %s.Background()\n", strconv.Quote(fl.op.Name), testing, m, context)
		b.WriteString("if k.Given != nil {\nif err := k.Given(ctx); err != nil {\nt.Fatalf(\"given: %v\", err)\n}\n}\n")
		args := "ctx"
		for _, field := range fl.fields() {
			args += ", k." + field
		}
		then := "k.Then(t)"
		if fl.hasValue() {
			fmt.Fprintf(&b, "got, err := ops.%s(%s)\n", m, args)
			then = "k.Then(t, got)"
		} else {
			fmt.Fprintf(&b, "err := ops.%s(%s)\n", m, args)
		}
		b.WriteString("if err != nil {\nt.Fatalf(\"want no error, got %v\", err)\n}\n")
		fmt.Fprintf(&b, "if k.Then != nil {\n%s\n}\n})\n", then)
	}
	b.WriteString("}\n\n")
	return b.String()
}

// requirements は、要求ごとの、テストの入れ物 Requirements（plugins/go-design/spec/go-design.hozo の Requirement.RequirementPort）:
// 要求ごとに、メソッド一つ（requirements に書いた分類の順、その中は、ケースの宣言順）。
func (f *file) requirements(classes []class) string {
	testing := f.use("testing")
	names := make([]string, len(classes))
	for i, c := range classes {
		names[i] = c.decl.Name
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// %s は、要求ごとの、テストの入れ物。要求（%s のケース）ごとに、メソッド一つ（宣言順）。中身は、人か AI が書く。\n"+
		"// メソッドが一つでも足りない値は、%s に渡すところでコンパイルできない。\ntype %s interface {\n",
		requirementsName, strings.Join(names, "、"), runReqsName, requirementsName)
	for _, c := range classes {
		for i := range c.cases {
			k := &c.cases[i]
			if lines := docLines(k.doc); len(lines) > 0 {
				fmt.Fprintf(&b, "// %s は、要求 %s: %s\n", k.method, k.label, lines[0])
				continued(&b, lines[1:])
			} else {
				fmt.Fprintf(&b, "// %s は、要求 %s。\n", k.method, k.label)
			}
			designs := "なし"
			if len(k.designs) > 0 {
				designs = strings.Join(k.designs, "、")
			}
			fmt.Fprintf(&b, "// 指している設計: %s\n%s(t *%s.T)\n", designs, k.method, testing)
		}
	}
	b.WriteString("}\n\n")
	return b.String()
}

// runRequirements は、走らせる関数 RunRequirements（同）: 要求ごとに、t.Run を一つ。テストの名前は、要求の名前。
func (f *file) runRequirements(classes []class) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s は、要求ごとに、入れ物を一つ走らせる。テストの名前は、要求の名前（<分類の FQN>.<ケース>）。\n"+
		"func %s(t *%s.T, c %s) {\n", runReqsName, runReqsName, f.use("testing"), requirementsName)
	for _, c := range classes {
		for i := range c.cases {
			k := &c.cases[i]
			// その場の関数で包む: RunRequirements の中に、要求ごとの行を持つ（テストの対応表が、その行を指す）
			fmt.Fprintf(&b, "t.Run(%s, func(t *%s.T) {\nc.%s(t)\n})\n", strconv.Quote(k.label), f.use("testing"), k.method)
		}
	}
	b.WriteString("}\n\n")
	return b.String()
}

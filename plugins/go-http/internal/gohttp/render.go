// このファイルは http.go のテキスト（docs/plugin-go-http.md「出力」「入力の読み方」「補助」）。検査（emit.go、inputs.go）を通った入力だけを
// 描く。期待する出力の実物は、サンプル tests/samples/shop-server/ の gen/server/http.go。
//
// 経路ごと、フィールドごとに出す行は、デコレータの引数（と、フィールドの名前）だけから作る: ここでは、フィールドの型も、戻り値の型も、
// 例外の引数（数も、名前も、型も）も、入力が Validate を持つかも、見ない（docs/requirements.md「出力を推論しない」）。見るのは、呼ぶ相手の、基底の
// メソッドの形（引数と戻り値を持つか）だけ（「出力」のハンドラの中の 4）。

// runtimePath は、生成したコードが import する runtime パッケージ（*runtime.ValidationError、runtime.Exception。
// docs/plugin-go-valid.md「runtime」、docs/plugin-go.md「runtime パッケージ」）。
const runtimePath = "github.com/mew-ton/hozo/runtime"

// file は、描いている途中の http.go。
type file struct {
	g  *generator
	im *golang.Imports
	// reserved は、このファイルが import するパッケージの名前（一度目に描いて決めたもの）。局所の名前が避ける。
	reserved map[string]bool
	// renamed は、補助が決まった名前で書くパッケージ（helperPackages）が、別の名前で import されたもの（あれば、生成器の不具合）。
	renamed []string
}

// local は、関数の中の局所の名前。このファイルが import するパッケージの名前と当たれば、当たらなくなるまで末尾に _ を足す
// （docs/plugin-go-http.md「出力」。docs/plugin-go.md「名前」の「局所の名前」と同じ扱い）。
func (f *file) local(name string) string {
	for f.reserved[name] {
		name += "_"
	}
	return name
}

// use は、補助が決まった名前で書くパッケージ path を import に足し、その名前を返す。
func (f *file) use(path string) string {
	want := helperPackages[path]
	if got := f.im.Add(path, want); got != want {
		f.renamed = append(f.renamed, fmt.Sprintf("%s が %s になった", path, got))
	}
	return want
}

// http は net/http のパッケージの名前。
func (f *file) http() string { return f.use("net/http") }

// render は http.go の全体を作り、go/format で整形する。import の名前を文書の決まりの順で決めるために、二度描く
// （docs/plugin-go.md「パッケージと import パス」の「import の名前」。基底と同じ手順）。
func (g *generator) render(routes []route) (string, error) {
	first := &file{g: g, im: golang.NewImports(g.view, g.layout, g.root, false)}
	first.draw(routes)
	second := &file{g: g, im: first.im.Canonical(), reserved: map[string]bool{}}
	for _, name := range second.im.Names() {
		second.reserved[name] = true
	}
	text := second.draw(routes)
	if err := second.im.Err(); err != nil {
		return "", fmt.Errorf("%s: %w（CFG-22 が通したはずのもの）", FileName, err)
	}
	if len(second.renamed) > 0 {
		return "", fmt.Errorf("%s: 補助が使うパッケージの import の名前が変わった（生成器の不具合）: %s", FileName, strings.Join(second.renamed, "、"))
	}
	src, err := format.Source([]byte(text))
	if err != nil {
		return "", fmt.Errorf("生成した %s を整形できない（生成器の不具合）: %w\n%s", FileName, err, text)
	}
	return string(src), nil
}

// draw は、ファイルのテキスト（整形前）を作る: ヘッダ、package 節、import、NewHandler、補助。
func (f *file) draw(routes []route) string {
	handler := f.handler(routes)
	helpers := f.helpers(routes)
	var b strings.Builder
	b.WriteString("// Code generated by hozoc " + TranspilerName + " " + plugin.Version + "; DO NOT EDIT.\n\n")
	b.WriteString("package " + f.g.layout.EntryName + "\n\n")
	b.WriteString(f.im.Render())
	b.WriteString("\n")
	b.WriteString(handler)
	b.WriteString(helpers)
	return b.String()
}

// pattern は、経路 r の http.ServeMux のパターン: `<メソッド> <パス>`。`/` で終わるパスは、ServeMux ではその下のすべてのパスに
// 合うので、そのパスだけに合うように `{$}` を足す（パスは、決まった文字列。docs/plugin-go-http.md「対象」）。
func pattern(r *route) string {
	p := r.method + " " + r.path
	if strings.HasSuffix(r.path, "/") {
		p += "{$}"
	}
	return p
}

// locals は、NewHandler とハンドラの中の局所の名前（docs/plugin-go-http.md「出力」）。
type locals struct {
	ops, mux, w, r, in, req, out, err string
}

// handler は NewHandler（docs/plugin-go-http.md「出力」）: コメント（経路の一覧）と、経路ごとの mux.HandleFunc。
func (f *file) handler(routes []route) string {
	l := locals{ops: f.local("ops"), mux: f.local("mux"), w: f.local("w"), r: f.local("r"),
		in: f.local("in"), req: f.local("req"), out: f.local("out"), err: f.local("err")}
	var b strings.Builder
	b.WriteString("// " + handlerName + " は ops を net/http のハンドラにする。@http.get / @http.post の付いた op ごとに経路を一つ持つ。\n")
	if f.g.opts.Validate {
		b.WriteString("// 入力を読んだ後、op を呼ぶ前に、入力の制約を確かめる（単位のオプション validate = true）。\n")
	}
	b.WriteString("//\n")
	width := 0
	for i := range routes {
		if n := len(routes[i].method + " " + routes[i].path); n > width {
			width = n
		}
	}
	for i := range routes {
		head := routes[i].method + " " + routes[i].path
		fmt.Fprintf(&b, "//\t%s%s  %s\n", head, strings.Repeat(" ", width-len(head)), routes[i].op.Name)
	}
	fmt.Fprintf(&b, "func %s(%s Ops) %s.Handler {\n%s := %s.NewServeMux()\n", handlerName, l.ops, f.http(), l.mux, f.http())
	for i := range routes {
		r := &routes[i]
		fmt.Fprintf(&b, "\n// %s\n%s.HandleFunc(%s, func(%s %s.ResponseWriter, %s *%s.Request) {\n%s})\n",
			r.op.Name, l.mux, strconv.Quote(pattern(r)), l.w, f.http(), l.r, f.http(), f.route(r, &l))
	}
	fmt.Fprintf(&b, "\nreturn %s\n}\n\n", l.mux)
	return b.String()
}

// route は、経路一つのハンドラの中（docs/plugin-go-http.md「出力」の 1〜5）。1、2、3、5 の行は、入力の model の宣言と、フィールドの
// 型と、戻り値の型によらず、同じ形。4 だけが、呼ぶ相手の、基底のメソッドの形（引数と戻り値を持つか）を写した二つの形を持つ。
func (f *file) route(r *route, l *locals) string {
	var b strings.Builder
	if r.model != nil {
		// 1: 入力を置く。どのフィールドも零値で始まる
		ns := f.g.declNS[r.model.Name]
		fmt.Fprintf(&b, "var %s %s%s\n", l.in, f.im.Qualifier(ns), golang.TypeName(r.model.Name, ns))
		// 2: 入力を読む。フィールドの順に、フィールドごとに一行
		fmt.Fprintf(&b, "%s := httpRequest{r: %s}\n", l.req, l.r)
		for i := range r.inputs {
			b.WriteString(f.read(&r.inputs[i], l))
		}
		fmt.Fprintf(&b, "if !%s.ok(%s) {\nreturn\n}\n", l.req, l.w)
		// 3: 制約の検査。入力が Validate を持つかどうかは、補助が実行時に見る
		if f.g.opts.Validate {
			fmt.Fprintf(&b, "if !httpValidate(%s, %s", l.w, l.in)
			for i := range r.inputs {
				fmt.Fprintf(&b, ", httpPlace{%s, %s}", strconv.Quote(r.inputs[i].field.Name), strconv.Quote(r.inputs[i].location()))
			}
			b.WriteString(") {\nreturn\n}\n")
		}
	}
	// 4: op を呼ぶ。行の形は、基底のメソッドの形（plugin/golang の Signature: 引数と戻り値を持つか）の写しで、振る舞いを運ばない
	call := fmt.Sprintf("%s.%s(%s.Context()", l.ops, golang.MethodName(r.op.Name), l.r)
	if r.model != nil {
		call += ", " + l.in
	}
	call += ")"
	fail := fmt.Sprintf("httpWriteError(%s, %s)\nreturn\n", l.w, l.err)
	result := "nil"
	if r.op.Returns != nil && !ir.IsNever(r.op.Returns) {
		result = l.out
		fmt.Fprintf(&b, "%s, %s := %s\nif %s != nil {\n%s}\n", l.out, l.err, call, l.err, fail)
	} else {
		fmt.Fprintf(&b, "if %s := %s; %s != nil {\n%s}\n", l.err, call, l.err, fail)
	}
	// 5: 成功を返す。ステータスも、本文も、ここには書かない（補助が、実行時に、渡された値で決める）
	fmt.Fprintf(&b, "httpWriteResult(%s, %s)\n", l.w, result)
	return b.String()
}

// read は、入力のフィールド一つを読む一行（docs/plugin-go-http.md「入力の読み方」の二つの表）。デコレータと、その引数（か、
// フィールドの名前）だけで決まる: メソッドはデコレータの名前、項目の形は最初の引数に項目の名前、@http.required と @http.default は
// 最後の引数。フィールドの型で変わるものは、何も足さない。
func (f *file) read(x *input, l *locals) string {
	method := strings.TrimPrefix(x.decorator, "http.")
	var args []string
	if !x.whole {
		args = append(args, strconv.Quote(x.name))
	}
	args = append(args, "&"+l.in+"."+golang.FieldName(x.field.Name))
	if x.required {
		args = append(args, "httpRequired")
	}
	if x.def != nil {
		args = append(args, "httpDefault("+f.literal(x.def)+")")
	}
	return fmt.Sprintf("%s.%s(%s)\n", l.req, method, strings.Join(args, ", "))
}

// literal は、@http.default のリテラルの、Go での書き方（docs/plugin-go.md「値」の表の literal の行。基底と同じ）。
// Duration は time.Duration(<ナノ秒>)。フィールドの型への変換は書かない（補助が、実行時に、読む先の型に変える）。
func (f *file) literal(lit ir.Literal) string {
	if _, ok := lit.(ir.DurationLiteral); ok {
		return f.im.Add("time", "time") + ".Duration(" + literalBody(lit) + ")"
	}
	return literalBody(lit)
}

// helpers は、NewHandler の後ろの補助（docs/plugin-go-http.md「補助」）: 使うものだけを、決まった順で出す。どれを使うかは、経路の
// 入力のデコレータと、単位のオプションだけで決まる。
func (f *file) helpers(routes []route) string {
	// ハンドラが呼ぶ httpRequest のメソッド
	var input, header, query, body, headerObj, queryObj, bodyObj bool
	for i := range routes {
		input = input || routes[i].model != nil
		for _, x := range routes[i].inputs {
			switch x.decorator {
			case httpHeader:
				header = true
			case httpQuery:
				query = true
			case httpBody:
				body = true
			case httpHeaderObj:
				headerObj = true
			case httpQueryObj:
				queryObj = true
			case httpBodyObj:
				bodyObj = true
			}
		}
	}
	// 全体の形は、項目の形のメソッドで、項目を一つずつ読む
	header, query = header || headerObj, query || queryObj
	text := header || query
	missing := text || body
	validate := f.g.opts.Validate && input
	statuses := f.g.statuses(routes)

	unions := len(f.g.unions) > 0
	var b strings.Builder
	add := func(on bool, h helper) {
		if !on {
			return
		}
		if unions {
			h = withUnions(h)
		}
		for _, p := range h.imports {
			f.use(p)
		}
		b.WriteString(h.text)
	}
	add(true, helperErrorBody)
	add(input, helperBadRequest)
	add(validate, helperPlace)
	add(missing, helperOptions)
	add(input, helperRequestHead)
	add(body, helperRequestItems)
	add(input, helperRequestTail)
	add(header, helperHeader)
	add(query, helperQuery)
	add(body, helperBody)
	add(headerObj, helperHeaderObj)
	add(queryObj, helperQueryObj)
	add(bodyObj, helperBodyObj)
	add(missing, helperMissing)
	add(text, helperText)
	add(input, helperOK)
	add(validate, helperValidate)
	add(true, helperWriteJSON)
	if unions {
		f.use("reflect")
		b.WriteString(f.g.unionTable(f.im.Qualifier))
		add(true, helperUnionCodec)
	}
	add(true, helperWriteResult)
	b.WriteString(f.writeError(statuses))
	add(len(statuses) > 0, helperThrown)
	return strings.TrimSuffix(b.String(), "\n")
}

// writeError は補助 httpWriteError（docs/plugin-go-http.md「補助」）: @http.status を持つ例外を、最初に現れた順に、例外ごとに一行
// `case httpThrown[<例外の型>](w, err, <code>):`。引数を持つ例外も、持たない例外も、同じ形で、引数の数と型は、行を変えない
// （例外の値をどう応答にするかは、補助 httpThrown が、実行時に見る）。
// 一つもなければ、switch を書かず、いつも 500。引数の名前（w、err）は、例外の名前空間のパッケージの名前と当たれば、末尾に _ を足す。
func (f *file) writeError(statuses []status) string {
	w, err := f.local("w"), f.local("err")
	var b strings.Builder
	b.WriteString(helperWriteErrorComment)
	fmt.Fprintf(&b, "func httpWriteError(%s %s.ResponseWriter, %s error) {\n", w, f.http(), err)
	internal := fmt.Sprintf("httpWriteJSON(%s, %s.StatusInternalServerError, httpErrorBody{Error: \"internal\"})\n", w, f.http())
	if len(statuses) == 0 {
		b.WriteString(internal + "}\n\n")
		return b.String()
	}
	b.WriteString("switch {\n")
	for _, s := range statuses {
		ns := f.g.declNS[s.exception.Name]
		fmt.Fprintf(&b, "case httpThrown[%s%s](%s, %s, %d):\n", f.im.Qualifier(ns), golang.TypeName(s.exception.Name, ns), w, err, s.code)
	}
	b.WriteString("default:\n" + internal + "}\n}\n\n")
	return b.String()
}

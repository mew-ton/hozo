// このファイルは http.go のテキスト（docs/plugin-go-http.md「出力」「入力の読み方」「補助」）。検査（emit.go）を通った入力だけを描く。
// 期待する出力の実物は、サンプル tests/samples/shop-server/ の gen/server/http.go。

// runtimePath は、生成したコードが import する runtime パッケージ（*runtime.ValidationError。docs/plugin-go-valid.md「runtime」）。
const runtimePath = "github.com/mew-ton/hozo/runtime"

// file は、描いている途中の http.go。
type file struct {
	g  *generator
	im *golang.Imports
	// reserved は、このファイルが import するパッケージの名前（一度目に描いて決めたもの）。局所の名前が避ける。
	reserved map[string]bool
	// 補助のうち、ハンドラが直に使ったもの（docs/plugin-go-http.md「補助」: 使うものだけを出す）。
	usesReadBody, usesBadRequest, usesInvalid bool
}

// local は、関数の中の局所の名前。このファイルが import するパッケージの名前と当たれば、当たらなくなるまで末尾に _ を足す。
func (f *file) local(name string) string {
	for f.reserved[name] {
		name += "_"
	}
	return name
}

// 標準ライブラリのパッケージ。使うときに import に足す（名前は変わらない。docs/plugin-go.md「パッケージと import パス」）。
func (f *file) http() string    { return f.im.Add("net/http", "http") }
func (f *file) strconv() string { return f.im.Add("strconv", "strconv") }

// render は http.go の全体を作り、go/format で整形する。import の名前を文書の決まりの順で決めるために、二度描く
// （docs/plugin-go.md「パッケージと import パス」の「import の名前」。基底と同じ手順）。
func (g *generator) render(routes []route) (string, error) {
	first := &file{g: g, im: golang.NewImports(g.view, g.layout, g.root, false)}
	first.draw(routes)
	second := &file{g: g, im: first.im.Canonical(), reserved: map[string]bool{}}
	for _, name := range second.im.Names() {
		second.reserved[name] = true
	}
	text := second.draw(routes)
	if err := second.im.Err(); err != nil {
		return "", fmt.Errorf("%s: %w（CFG-22 が通したはずのもの）", FileName, err)
	}
	src, err := format.Source([]byte(text))
	if err != nil {
		return "", fmt.Errorf("生成した %s を整形できない（生成器の不具合）: %w\n%s", FileName, err, text)
	}
	return string(src), nil
}

// draw は、ファイルのテキスト（整形前）を作る: ヘッダ、package 節、import、NewHandler、補助。
func (f *file) draw(routes []route) string {
	handler := f.handler(routes)
	helpers := f.helpers(routes)
	var b strings.Builder
	b.WriteString("// Code generated by hozoc " + TranspilerName + " " + plugin.Version + "; DO NOT EDIT.\n\n")
	b.WriteString("package " + f.g.layout.EntryName + "\n\n")
	b.WriteString(f.im.Render())
	b.WriteString("\n")
	b.WriteString(handler)
	b.WriteString(helpers)
	return b.String()
}

// pattern は、経路 r の http.ServeMux のパターン: `<メソッド> <パス>`。`/` で終わるパスは、ServeMux ではその下のすべてのパスに
// 合うので、そのパスだけに合うように `{$}` を足す（パスは、決まった文字列。docs/plugin-go-http.md「対象」）。
func pattern(r *route) string {
	p := r.method + " " + r.path
	if strings.HasSuffix(r.path, "/") {
		p += "{$}"
	}
	return p
}

// handler は NewHandler（docs/plugin-go-http.md「出力」）: コメント（経路の一覧）と、経路ごとの mux.HandleFunc。
func (f *file) handler(routes []route) string {
	var b strings.Builder
	b.WriteString("// " + handlerName + " は ops を net/http のハンドラにする。@http.get / @http.post の付いた op ごとに経路を一つ持つ。\n")
	if f.g.opts.Validate {
		b.WriteString("// 入力を読んだ後、op を呼ぶ前に、入力の制約を確かめる（単位のオプション validate = true）。\n")
	}
	b.WriteString("//\n")
	width := 0
	for i := range routes {
		if n := len(routes[i].method + " " + routes[i].path); n > width {
			width = n
		}
	}
	for i := range routes {
		head := routes[i].method + " " + routes[i].path
		fmt.Fprintf(&b, "//\t%s%s  %s\n", head, strings.Repeat(" ", width-len(head)), routes[i].op.Name)
	}
	ops, mux := f.local("ops"), f.local("mux")
	fmt.Fprintf(&b, "func %s(%s Ops) %s.Handler {\n%s := %s.NewServeMux()\n", handlerName, ops, f.http(), mux, f.http())
	for i := range routes {
		r := &routes[i]
		w, req := f.local("w"), f.local("r")
		fmt.Fprintf(&b, "\n// %s\n%s.HandleFunc(%s, func(%s %s.ResponseWriter, %s *%s.Request) {\n%s})\n",
			r.op.Name, mux, strconv.Quote(pattern(r)), w, f.http(), req, f.http(), f.route(r, ops, w, req))
	}
	fmt.Fprintf(&b, "\nreturn %s\n}\n\n", mux)
	return b.String()
}

// route は、経路一つのハンドラの中（docs/plugin-go-http.md「出力」の 1〜5）。ops、w、req は、NewHandler の引数と、ハンドラの
// 引数の名前。
func (f *file) route(r *route, ops, w, req string) string {
	var b strings.Builder
	in := f.local("in")
	// 1: 入力の初めの値
	if r.model != nil {
		ns := f.g.declNS[r.model.Name]
		name := golang.TypeName(r.model.Name, ns)
		if hasDefaults(r.model) {
			fmt.Fprintf(&b, "%s := %sNew%s()\n", in, f.im.Qualifier(ns), name)
		} else {
			fmt.Fprintf(&b, "var %s %s%s\n", in, f.im.Qualifier(ns), name)
		}
	}
	// 2: 入力を読む（フィールドの順）
	wroteBody := false
	for i := range r.inputs {
		x := &r.inputs[i]
		switch x.place {
		case inHeader:
			b.WriteString(f.readHeader(x, in, w, req))
		case inQuery:
			b.WriteString(f.readQuery(x, in, w, req))
		case inBody:
			if r.bodies() == 1 {
				b.WriteString(f.readBody("&"+in+"."+golang.FieldName(x.field.Name), w, req))
			} else if !wroteBody {
				// 二つ以上の @http.body は、最初のものの位置で、本文をまとめて読む
				b.WriteString(f.readBodies(r, in, w, req))
				wroteBody = true
			}
		}
	}
	// 3: 制約の検査
	err := f.local("err")
	if r.validate {
		f.usesInvalid = true
		var places []string
		for i := range r.inputs {
			places = append(places, fmt.Sprintf("httpPlace{%s, %s}", strconv.Quote(r.inputs[i].field.Name), strconv.Quote(r.location(&r.inputs[i]))))
		}
		fmt.Fprintf(&b, "if %s := %s.Validate(); %s != nil {\nhttpWriteInvalid(%s, %s", err, in, err, w, err)
		for _, p := range places {
			b.WriteString(", " + p)
		}
		b.WriteString(")\nreturn\n}\n")
	}
	// 4: op を呼ぶ
	call := fmt.Sprintf("%s.%s(%s.Context()", ops, golang.MethodName(r.op.Name), req)
	if r.model != nil {
		call += ", " + in
	}
	call += ")"
	fail := fmt.Sprintf("httpWriteError(%s, %s)\nreturn\n", w, err)
	returns := r.op.Returns
	if ir.IsNever(returns) {
		returns = nil
	}
	if returns == nil {
		// 5: 戻り値がなければ 204
		fmt.Fprintf(&b, "if %s := %s; %s != nil {\n%s}\n%s.WriteHeader(%s.StatusNoContent)\n", err, call, err, fail, w, f.http())
		return b.String()
	}
	out := f.local("out")
	fmt.Fprintf(&b, "%s, %s := %s\nif %s != nil {\n%s}\n", out, err, call, err, fail)
	// 5: 戻り値の型が配列なら、空の配列は必ず [] で返す
	t := returns
	if c, ok := t.(ir.CaseType); ok {
		t = c.Of
	}
	if _, isArray := t.(ir.ArrayType); isArray {
		fmt.Fprintf(&b, "if %s == nil {\n%s = %s{}\n}\n", out, out, golang.GoType(t, f.im))
	}
	fmt.Fprintf(&b, "httpWriteJSON(%s, %s.StatusOK, %s)\n", w, f.http(), out)
	return b.String()
}

// hasDefaults は、既定値を持つフィールドが一つでもあるか（基底が New<Model> を出す model。docs/plugin-go.md「model」）。
// IR にフィールドの既定値はなくなった（版 0.5。docs/ir.md「版」）ので、いつも false。
func hasDefaults(m *ir.Model) bool {
	return false
}

// badRequest は、要求を読めなかったときの終わり方: 決まった文言で httpWriteBadRequest を呼んで、ハンドラを終える。
func (f *file) badRequest(w, message string) string {
	f.usesBadRequest = true
	return fmt.Sprintf("httpWriteBadRequest(%s, %s)\nreturn\n", w, strconv.Quote(message))
}

// convert は、核の型の値の式 expr を、型 t（核の型か、それを元に持つ scalar）の値の式にする。
func (f *file) convert(expr string, t ir.Type) string {
	if _, isCore := t.(ir.CoreType); isCore {
		return expr
	}
	return golang.GoType(t, f.im) + "(" + expr + ")"
}

// required は、フィールド x が、要求になければならないか（省略可能でも、既定値持ちでもない）。
func required(x *input) bool { return !x.optional }

// readHeader は @http.header のフィールド（docs/plugin-go-http.md「入力の読み方」の表の上の二行）。値は、そのまま型にする。
// 空の文字列のヘッダは、ないものとして読む。
func (f *file) readHeader(x *input, in, w, req string) string {
	v, target := f.local("v"), in+"."+golang.FieldName(x.field.Name)
	var b strings.Builder
	fmt.Fprintf(&b, "if %s := %s.Header.Get(%s); %s != \"\" {\n", v, req, strconv.Quote(x.header), v)
	switch {
	case !x.optional:
		fmt.Fprintf(&b, "%s = %s\n", target, f.convert(v, x.value))
	case f.convert(v, x.value) == v:
		fmt.Fprintf(&b, "%s = &%s\n", target, v)
	default:
		tmp := f.local("x")
		fmt.Fprintf(&b, "%s := %s\n%s = &%s\n", tmp, f.convert(v, x.value), target, tmp)
	}
	if required(x) {
		b.WriteString("} else {\n" + f.badRequest(w, "header "+x.header+": missing"))
	}
	b.WriteString("}\n")
	return b.String()
}

// readQuery は @http.query のフィールド（同、三行目と「クエリの値の読み方」）: あれば、フィールドの型で読んで入れる。
// なければ、初めの値のまま。省略可能でも既定値持ちでもないフィールドで、なければ、読めない要求。
func (f *file) readQuery(x *input, in, w, req string) string {
	name := x.field.Name
	q, tmp, target := f.local("q"), f.local("x"), in+"."+golang.FieldName(name)
	get := fmt.Sprintf("%s.Get(%s)", q, strconv.Quote(name))
	var b strings.Builder
	fmt.Fprintf(&b, "if %s := %s.URL.Query(); %s.Has(%s) {\n", q, req, q, strconv.Quote(name))
	value := get // フィールドの型の値の式
	if x.core != ir.CoreString {
		var parse, kind string
		switch x.core {
		case ir.CoreInt:
			parse, kind = fmt.Sprintf("%s.ParseInt(%s, 10, 64)", f.strconv(), get), "int"
		case ir.CoreFloat:
			parse, kind = fmt.Sprintf("%s.ParseFloat(%s, 64)", f.strconv(), get), "float"
		default:
			parse, kind = fmt.Sprintf("%s.ParseBool(%s)", f.strconv(), get), "boolean"
		}
		err := f.local("err")
		fmt.Fprintf(&b, "%s, %s := %s\nif %s != nil {\n%s}\n", tmp, err, parse, err, f.badRequest(w, "query "+name+": invalid "+kind))
		value = tmp
	}
	converted := f.convert(value, x.value)
	switch {
	case !x.optional:
		fmt.Fprintf(&b, "%s = %s\n", target, converted)
	case converted == tmp:
		fmt.Fprintf(&b, "%s = &%s\n", target, tmp)
	default:
		// アドレスを取るために、フィールドの型の値を、局所の変数に置く
		addr := tmp
		if value == tmp {
			addr = f.local("y")
		}
		fmt.Fprintf(&b, "%s := %s\n%s = &%s\n", addr, converted, target, addr)
	}
	if required(x) {
		b.WriteString("} else {\n" + f.badRequest(w, "query "+name+": missing"))
	}
	b.WriteString("}\n")
	return b.String()
}

// readBody は、本文の JSON を、target（ポインタの式）に読む。読めなければ、文言 `body: invalid JSON`。
func (f *file) readBody(target, w, req string) string {
	f.usesReadBody = true
	err := f.local("err")
	return fmt.Sprintf("if %s := httpReadBody(%s, %s); %s != nil {\n%s}\n", err, req, target, err, f.badRequest(w, "body: invalid JSON"))
}

// readBodies は、二つ以上の @http.body のフィールド（docs/plugin-go-http.md「入力の読み方」の表の最後の行）: 本文は、フィールド名を
// キーにした JSON のオブジェクト。@http.body のフィールドだけを、同じ名前と型と json タグで持つ無名の構造体 body に、
// 初めの値を入れてから読み、フィールドに写す。
func (f *file) readBodies(r *route, in, w, req string) string {
	body := f.local("body")
	var fields, init, copies strings.Builder
	for i := range r.inputs {
		x := &r.inputs[i]
		if x.place != inBody {
			continue
		}
		name := golang.FieldName(x.field.Name)
		tag := x.field.Name
		if x.optional {
			tag += ",omitempty"
		}
		fmt.Fprintf(&fields, "%s %s `json:\"%s\"`\n", name, golang.GoType(x.field.Type, f.im), tag)
		fmt.Fprintf(&init, "%s: %s.%s, ", name, in, name)
		fmt.Fprintf(&copies, "%s.%s = %s.%s\n", in, name, body, name)
	}
	return fmt.Sprintf("%s := struct {\n%s}{%s}\n%s%s", body, fields.String(), strings.TrimSuffix(init.String(), ", "),
		f.readBody("&"+body, w, req), copies.String())
}

// helpers は、NewHandler の後ろの補助（docs/plugin-go-http.md「補助」）: 使うものだけを、決まった順で出す。
// 中身は、サンプルの gen/server/http.go の通り。
func (f *file) helpers(routes []route) string {
	statuses := f.g.statuses(routes)
	bad := f.usesBadRequest || f.usesInvalid
	var b strings.Builder
	b.WriteString(`// httpErrorBody は失敗の応答の本文。
type httpErrorBody struct {
	// 例外の FQN。op を呼ぶ前の失敗は "http.BadRequest"、中身を出さない失敗は "internal"。
	Error string ` + "`json:\"error\"`" + `
	// 例外が運ぶ値。
	Value any ` + "`json:\"value,omitempty\"`" + `
}

`)
	if bad {
		b.WriteString(`// httpBadRequest は "http.BadRequest" が運ぶ値。
type httpBadRequest struct {
	// 理由。要求を読めなかったなら "<場所>: <理由>"、制約に合わなかったなら "invalid input"。
	Message string ` + "`json:\"message\"`" + `
	// 制約の違反。要求を読めなかったなら空。
	Violations []httpViolation ` + "`json:\"violations\"`" + `
}

// httpViolation は制約の違反一つ。
type httpViolation struct {
	// 通信の上の場所: body、query.<名前>、header.<名前> と、その中のパス（body.email、body[0].quantity）。
	Path string ` + "`json:\"path\"`" + `
	// 違反した制約の名前（valid の語彙のデコレータの名前）。
	Constraint string ` + "`json:\"constraint\"`" + `
}

`)
	}
	if f.usesInvalid {
		b.WriteString(`// httpPlace は、入力の model のフィールドと、それを読む通信の上の場所の組。
type httpPlace struct{ field, place string }

`)
	}
	if f.usesReadBody {
		fmt.Fprintf(&b, `// httpReadBody は要求の本文を JSON の値一つとして v に読む。
func httpReadBody(r *%[1]s.Request, v any) error {
	data, err := %[2]s.ReadAll(r.Body)
	if err != nil {
		return err
	}
	return %[3]s.Unmarshal(data, v)
}

`, f.http(), f.im.Add("io", "io"), f.im.Add("encoding/json", "json"))
	}
	fmt.Fprintf(&b, `// httpWriteJSON は v を JSON にして status で返す。
func httpWriteJSON(w %[1]s.ResponseWriter, status int, v any) {
	data, err := %[2]s.Marshal(v)
	if err != nil {
		status, data = %[1]s.StatusInternalServerError, []byte(`+"`{\"error\":\"internal\"}`"+`)
	}
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(status)
	_, _ = w.Write(data)
}

`, f.http(), f.im.Add("encoding/json", "json"))
	if f.usesBadRequest {
		fmt.Fprintf(&b, `// httpWriteBadRequest は、要求を op の入力に読めなかったときの 400。op は呼ばない。
func httpWriteBadRequest(w %[1]s.ResponseWriter, message string) {
	httpWriteJSON(w, %[1]s.StatusBadRequest, httpErrorBody{
		Error: "http.BadRequest",
		Value: httpBadRequest{Message: message, Violations: []httpViolation{}},
	})
}

`, f.http())
	}
	if f.usesInvalid {
		fmt.Fprintf(&b, `// httpWriteInvalid は、読んだ入力が制約に合わなかったときの 400。op は呼ばない。err は入力の Validate が返したもの。
// 違反の Path の先頭（入力の model のフィールド名）を、places の通りに通信の上の場所に置き換える。
func httpWriteInvalid(w %[1]s.ResponseWriter, err error, places ...httpPlace) {
	var invalid *%[2]s.ValidationError
	if !%[3]s.As(err, &invalid) {
		httpWriteError(w, err)
		return
	}
	violations := make([]httpViolation, 0, len(invalid.Violations))
	for _, x := range invalid.Violations {
		path := x.Path
		for _, p := range places {
			rest, ok := %[4]s.CutPrefix(path, p.field)
			if ok && (rest == "" || rest[0] == '.' || rest[0] == '[') {
				path = p.place + rest
				break
			}
		}
		violations = append(violations, httpViolation{Path: path, Constraint: x.Constraint})
	}
	httpWriteJSON(w, %[1]s.StatusBadRequest, httpErrorBody{
		Error: "http.BadRequest",
		Value: httpBadRequest{Message: "invalid input", Violations: violations},
	})
}

`, f.http(), f.im.Add(runtimePath, "runtime"), f.im.Add("errors", "errors"), f.im.Add("strings", "strings"))
	}
	b.WriteString(f.writeError(statuses))
	return b.String()
}

// writeError は補助 httpWriteError（docs/plugin-go-http.md「補助」）: @http.status を持つ例外を、最初に現れた順に e0、e1、… として、
// errors.As で値の型を見分ける。一つもなければ、switch を書かず、いつも 500。
func (f *file) writeError(statuses []status) string {
	w, err := f.local("w"), f.local("err")
	var b strings.Builder
	b.WriteString("// httpWriteError は op が返したエラーを応答にする。@http.status を持つ例外は、そのステータスと例外の FQN（と運ぶ値）。\n")
	b.WriteString("// それ以外（ステータスを持たない例外、ctx のエラー、ほかのエラー）は 500 で、中身を出さない。\n")
	fmt.Fprintf(&b, "func httpWriteError(%s %s.ResponseWriter, %s error) {\n", w, f.http(), err)
	internal := fmt.Sprintf("httpWriteJSON(%s, %s.StatusInternalServerError, httpErrorBody{Error: \"internal\"})\n", w, f.http())
	if len(statuses) == 0 {
		b.WriteString(internal + "}\n")
		return b.String()
	}
	b.WriteString("var (\n")
	names := make([]string, len(statuses))
	for i, s := range statuses {
		ns := f.g.declNS[s.exception.Name]
		names[i] = f.local("e" + strconv.Itoa(i))
		fmt.Fprintf(&b, "%s %s%s\n", names[i], f.im.Qualifier(ns), golang.TypeName(s.exception.Name, ns))
	}
	b.WriteString(")\nswitch {\n")
	for i, s := range statuses {
		value := ""
		if s.exception.Value != nil {
			value = ", Value: " + names[i] + ".Value"
		}
		fmt.Fprintf(&b, "case %s.As(%s, &%s):\nhttpWriteJSON(%s, %d, httpErrorBody{Error: %s%s})\n",
			f.im.Add("errors", "errors"), err, names[i], w, s.code, strconv.Quote(s.exception.Name), value)
	}
	b.WriteString("default:\n" + internal + "}\n}\n")
	return b.String()
}

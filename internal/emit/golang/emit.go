// Version は生成したファイルのヘッダに書く hozoc の版（docs/emit-go.md「配置」）。
// 当面は固定の文字列。hozoc の版の持ち主は docs/cli.md で、cmd/hozoc がビルド時に埋める値
// （-ldflags か debug.ReadBuildInfo）を internal/app から渡す形にするまでの仮置き。
const Version = "0.0.0-dev"

// Header はすべての生成ファイルの先頭の行。
var Header = "// Code generated by hozoc " + Version + "; DO NOT EDIT.\n"

// File は書き出すファイル一つ。Path はプロジェクトのルートからの相対パス（`/` 区切り）。
type File struct {
	Path    string
	Content []byte
}

// ManifestInfo は Conf(viewer).plugins の各マニフェストのうち、包む関数を作るかどうかの判定
// （docs/emit-go.md「デコレータ」）に要る部分。Entry / Stop / Decorate はデコレータの FQN。
type ManifestInfo struct {
	Name     string
	Entry    []string
	Stop     []string
	Decorate []string
}

// Options は Emit の入力のうち View にないもの。
type Options struct {
	// Root はプロジェクトのルート（hozo.toml のあるディレクトリ）。go.mod の探索（GOEMIT-1）と、
	// 整形に失敗したときの `<out>/.hozoc-failed/` の書き出し先に使う。
	Root string
	// Manifests は Conf(viewer).plugins のマニフェスト。entry / stop に含まれるデコレータは包む関数にしない。
	Manifests []ManifestInfo
}

// 診断のコード（docs/emit-go.md「診断」）。
const (
	CodeNoGoMod       = "GOEMIT-1"
	CodeNameCollision = "GOEMIT-2"
	CodeBadConstraint = "GOEMIT-3"
	CodeBadDefault    = "GOEMIT-4"
	// CodeInternal は生成器の不具合（整形に失敗した、など）。
	CodeInternal = "GOEMIT-INTERNAL"
)

// FailedDir は整形に失敗したファイルを置く、out の下のディレクトリ（docs/emit-go.md「配置」）。
const FailedDir = ".hozoc-failed"

// Emit は view の名前空間の Go のファイルを作る（docs/emit-go.md）。
// 返すファイルの Path はプロジェクトのルートからの相対パス。
// error の診断が一つでもあればファイルは返さない。
func Emit(view *ir.View, opts Options) ([]File, []diag.Diagnostic) {
	if view == nil || view.Program == nil {
		return nil, []diag.Diagnostic{{Severity: diag.Error, Code: CodeInternal, Message: "emit: View か Program が nil"}}
	}
	ns := view.Program.Namespace(view.Viewer)
	if ns == nil {
		return nil, []diag.Diagnostic{{Severity: diag.Error, Code: CodeInternal,
			Message: fmt.Sprintf("emit: 名前空間 %q が Program にない", view.Viewer)}}
	}
	e := newEmitter(view, ns, opts)
	files := e.run()
	if errs, _ := diag.Count(e.diags); errs > 0 {
		return nil, e.diags
	}
	return files, e.diags
}

// emitter は一度の Emit の状態。
type emitter struct {
	view   *ir.View
	prog   *ir.Program
	ns     *ir.Namespace
	viewer string
	opts   Options
	diags  []diag.Diagnostic

	pkg string // Go のパッケージ名
	dir string // ルートからの出力ディレクトリ（`/` 区切り）: Dir(viewer) = View.Config.Dir

	declNS   map[string]string // FQN → 宣言を持つ名前空間
	copied   map[string]bool   // viewer のパッケージに複製する宣言の FQN
	pkgPaths map[string]string // 名前空間 → import パス（Go の名前空間だけ）

	// パッケージに出す宣言（viewer の宣言の順、その後に複製を Program の順で）
	models     []*ir.Model
	scalars    []*ir.Scalar
	unions     []*ir.Union
	exceptions []*ir.Exception
	effects    []*ir.Effect
	classifies []*ir.Classify
	ops        []*ir.Op
	// stateCases は StateCases に述語を出す状態（docs/emit-go.md「state」）: viewer の list / nullable の基底の状態を宣言の順で。
	stateCases []*ir.State

	// 配線を見て集めるもの
	projections []projection // 必要になった射影の組（順序は必要になった順）
	usedStates  []string     // States の取得メソッドを出す状態の FQN（Program の順）
	depsNS      []string     // Deps のフィールドにする名前空間（Program の順）
	depsOps     map[string][]string
	needPtr     bool // wiring.go に ptr ヘルパーが要るか
	// matchesState は viewer の配線に match s by list / by nullable があるか。あるときだけ New が stateCases を取る。
	matchesState bool

	wrappers map[string][]wrapper // op の FQN → 包む関数（内側から順）

	copyNote string // 複製した宣言を出している間、そのコメントに足す文
}

// projection は model から model への変換関数 <From>To<To>（docs/emit-go.md「配線の本体」の「射影」）。
type projection struct{ from, to string }

func newEmitter(view *ir.View, ns *ir.Namespace, opts Options) *emitter {
	e := &emitter{
		view:     view,
		prog:     view.Program,
		ns:       ns,
		viewer:   view.Viewer,
		opts:     opts,
		declNS:   map[string]string{},
		copied:   map[string]bool{},
		pkgPaths: map[string]string{},
		depsOps:  map[string][]string{},
		wrappers: map[string][]wrapper{},
	}
	for i := range e.prog.Namespaces {
		n := &e.prog.Namespaces[i]
		for _, d := range n.Decls {
			if d != nil {
				e.declNS[d.Common().Name] = n.Name
			}
		}
	}
	return e
}

// run は docs/emit-go.md を上から順に実行する。
func (e *emitter) run() []File {
	e.pkg = gol.PackageName(e.viewer)
	e.dir = dirOf(e.view.Config)
	if _, err := gol.ImportPath(e.opts.Root, e.dir); err != nil {
		e.errorf(CodeNoGoMod, nil, "名前空間 %s の out %q の上に go.mod がない: %v", e.viewer, e.view.Config.Out, err)
		return nil
	}

	e.collectDecls()
	e.checkNames()
	e.collectWrappers()

	// 配線と op を先に作り、射影・状態・Deps を集める。
	wiring := e.genWiring()
	ops := e.genOps()
	classify := e.genClassify()
	types := e.genTypes()
	validate := e.genValidate()
	doc := e.genDoc()

	var files []File
	for _, g := range []*genFile{doc, types, validate, ops, wiring, classify} {
		if g == nil || g.body.Len() == 0 && g.pkgDoc == "" {
			continue
		}
		if f, ok := e.finish(g); ok {
			files = append(files, f)
		}
	}
	return files
}

// genFile は作る途中のファイル一つ。imports は GoType が足す。
type genFile struct {
	name    string
	imports gol.Imports
	body    bytes.Buffer
	// pkgDoc は doc.go のパッケージコメント（package 節の直前）。
	pkgDoc string
}

func (e *emitter) newFile(name string) *genFile {
	g := &genFile{name: name}
	g.imports.Viewer = e.viewer
	g.imports.Resolve = e.resolve
	return g
}

func (g *genFile) printf(format string, args ...any) {
	fmt.Fprintf(&g.body, format, args...)
}

func (g *genFile) println(s string) {
	g.body.WriteString(s)
	g.body.WriteByte('\n')
}

// finish はヘッダ・package 節・import を付けて整形する。整形に失敗したら
// 整形前の内容を <out>/.hozoc-failed/<file> に書き、内部エラーの診断を出す。
func (e *emitter) finish(g *genFile) (File, bool) {
	var buf bytes.Buffer
	buf.WriteString(Header)
	buf.WriteString("\n")
	if g.pkgDoc != "" {
		buf.WriteString(g.pkgDoc)
	}
	buf.WriteString("package " + e.pkg + "\n\n")
	if imp := g.imports.Render(); imp != "" {
		buf.WriteString(imp)
		buf.WriteString("\n")
	}
	buf.Write(g.body.Bytes())
	rel := path.Join(e.dir, g.name)
	out, err := format.Source(buf.Bytes())
	if err != nil {
		failed := filepath.Join(e.opts.Root, filepath.FromSlash(e.dir), FailedDir, g.name)
		where := failed
		if werr := os.MkdirAll(filepath.Dir(failed), 0o755); werr == nil {
			if werr = os.WriteFile(failed, buf.Bytes(), 0o644); werr != nil {
				where = fmt.Sprintf("%s（書けなかった: %v）", failed, werr)
			}
		} else {
			where = fmt.Sprintf("%s（書けなかった: %v）", failed, werr)
		}
		e.errorf(CodeInternal, nil, "生成器の不具合: %s を go/format で整形できない: %v。整形前の内容を %s に書いた", rel, err, where)
		return File{}, false
	}
	return File{Path: rel, Content: out}, true
}

// errorf は error の診断を足す。span が nil でなければファイルと位置をメッセージに付ける。
func (e *emitter) errorf(code string, span *ir.Span, format string, args ...any) {
	d := diag.Diagnostic{Severity: diag.Error, Code: code, Message: fmt.Sprintf(format, args...)}
	if span != nil {
		d.File = span.File
		d.Message += fmt.Sprintf("（%s:%d:%d）", span.File, span.Start.Line, span.Start.Col)
	}
	e.diags = append(e.diags, d)
}

// lookup は FQN の宣言。なければ nil。
func (e *emitter) lookup(fqn string) ir.Decl { return e.prog.Lookup(fqn) }

func (e *emitter) model(fqn string) *ir.Model {
	m, _ := e.lookup(fqn).(*ir.Model)
	return m
}

func (e *emitter) scalar(fqn string) *ir.Scalar {
	s, _ := e.lookup(fqn).(*ir.Scalar)
	return s
}

func (e *emitter) union(fqn string) *ir.Union {
	u, _ := e.lookup(fqn).(*ir.Union)
	return u
}

func (e *emitter) op(fqn string) *ir.Op {
	o, _ := e.lookup(fqn).(*ir.Op)
	return o
}

// typeName は FQN の Go の型名（パッケージの修飾なし）。
func (e *emitter) typeName(fqn string) string {
	return gol.TypeName(fqn, e.declNS[fqn])
}

// localName は FQN の最後のセグメント（宣言名）。
func localName(fqn string) string {
	if i := strings.LastIndexByte(fqn, '.'); i >= 0 {
		return fqn[i+1:]
	}
	return fqn
}

// Version は生成したファイルのヘッダに書く hozoc の版（docs/emit-go.md「配置」）。
// 当面は固定の文字列。hozoc の版の持ち主は docs/cli.md で、cmd/hozoc がビルド時に埋める値
// （-ldflags か debug.ReadBuildInfo）を internal/app から渡す形にするまでの仮置き。
const Version = "0.0.0-dev"

// Header はすべての生成ファイルの先頭の行。
var Header = "// Code generated by hozoc " + Version + "; DO NOT EDIT.\n"

// File は書き出すファイル一つ。Path はプロジェクトのルートからの相対パス（`/` 区切り）。
type File struct {
	Path    string
	Content []byte
}

// Options は Emit の入力のうち View にないもの。
type Options struct {
	// Root はプロジェクトのルート（hozo.toml のあるディレクトリ）。go.mod の探索（GOEMIT-1）と、
	// 整形に失敗したときの `<out>/.hozoc-failed/` の書き出し先に使う。
	Root string
	// Select は、単位のトランスパイラが view の名前空間について返した select を合わせたもの（docs/plugin-protocol.md「選択」）。
	// ここから出力の対象が決まる（docs/emit-go.md「出力の対象」）。何も選ばれていなければ、ファイルは一つも出ない。
	Select plugin.Select
	// Exported は、別の名前空間の型の FQN → その型を持つ Go の出力のディレクトリ（Dir(U', M)。ルートからの相対パス）。
	// その名前空間を出力する Go の単位のうち、設定の順で最初に出力がその型を持つ（[Exports]）ものを、呼ぶ側が決めて入れる。
	// ここにある型はそのパッケージを import して使い、ない型は viewer のパッケージに複製する（docs/emit-go.md「配置」）。
	Exported map[string]string
}

// 診断のコード（docs/emit-go.md「診断」）。
const (
	CodeNoGoMod       = "GOEMIT-1"
	CodeNameCollision = "GOEMIT-2"
	CodeBadConstraint = "GOEMIT-3"
	CodeBadDefault    = "GOEMIT-4"
	// CodeImportCycle は出力どうしの import の循環。判定は呼ぶ側（internal/app）が [Imports] から行う。
	CodeImportCycle = "GOEMIT-5"
	// CodeInternal は生成器の不具合（整形に失敗した、など）。
	CodeInternal = "GOEMIT-INTERNAL"
)

// FailedDir は整形に失敗したファイルを置く、out の下のディレクトリ（docs/emit-go.md「配置」）。
const FailedDir = ".hozoc-failed"

// Emit は view の名前空間の Go のファイルを作る（docs/emit-go.md）。出すのは opts.Select から決まる出力の対象だけで、
// 何も選ばれていなければファイルも診断も返さない。返すファイルの Path はプロジェクトのルートからの相対パス。
// error の診断が一つでもあればファイルは返さない。
func Emit(view *ir.View, opts Options) ([]File, []diag.Diagnostic) {
	e, diags := prepare(view, opts)
	if e == nil {
		return nil, diags
	}
	files := e.run()
	if errs, _ := diag.Count(e.diags); errs > 0 {
		return nil, e.diags
	}
	return files, e.diags
}

// Exports は、sel から決まる出力の対象のうち、view の名前空間で宣言された型（model / scalar / union / exception）の
// FQN を宣言の順で返す。その名前空間のパッケージが持つ型で、別の Go の名前空間の出力はこれを import して使える
// （[Options.Exported]。docs/emit-go.md「配置」）。別の名前空間の選択にはよらない。
func Exports(view *ir.View, sel plugin.Select) []string {
	e, _ := prepare(view, Options{Select: sel})
	if e == nil {
		return nil
	}
	e.collect()
	var out []string
	for _, d := range e.ns.Decls {
		if d != nil && e.reach[d.Common().Name] {
			out = append(out, d.Common().Name)
		}
	}
	return out
}

// Imports は、[Emit] が作るファイルが import する、別の出力のディレクトリ（[Options.Exported] の値）を辞書順で返す。
// 出力どうしの import の循環（GOEMIT-5。docs/emit-go.md「配置」）を呼ぶ側が確かめるためのもの。見るのは実際に作った
// ファイルの import で、型を参照するだけで import しないもの（複製した型の先など）は数えない。
// 何も選ばれていない、またはファイルを作れなければ nil。
func Imports(view *ir.View, opts Options) []string {
	e, _ := prepare(view, opts)
	if e == nil {
		return nil
	}
	e.run()
	if errs, _ := diag.Count(e.diags); errs > 0 {
		return nil
	}
	out := make([]string, 0, len(e.imported))
	for dir := range e.imported {
		out = append(out, dir)
	}
	sort.Strings(out)
	return out
}

// Uses は、sel から決まる出力の対象が型を参照している、別の名前空間の名前を Program の順で返す。呼ぶ側は、その名前空間を
// 出力する Go の単位の [Exports] から [Options.Exported] を作って Emit を呼ぶ。
func Uses(view *ir.View, sel plugin.Select) []string {
	e, _ := prepare(view, Options{Select: sel})
	if e == nil {
		return nil
	}
	e.collect()
	var out []string
	for i := range e.prog.Namespaces {
		n := &e.prog.Namespaces[i]
		if n.Name == e.viewer {
			continue
		}
		for _, d := range n.Decls {
			if d != nil && e.reach[d.Common().Name] {
				out = append(out, n.Name)
				break
			}
		}
	}
	return out
}

// prepare は Emit / Exports / Uses の共通の前半: View を確かめ、emitter を作る。View が使えなければ nil と診断。
func prepare(view *ir.View, opts Options) (*emitter, []diag.Diagnostic) {
	if view == nil || view.Program == nil {
		return nil, []diag.Diagnostic{{Severity: diag.Error, Code: CodeInternal, Message: "emit: View か Program が nil"}}
	}
	ns := view.Program.Namespace(view.Viewer)
	if ns == nil {
		return nil, []diag.Diagnostic{{Severity: diag.Error, Code: CodeInternal,
			Message: fmt.Sprintf("emit: 名前空間 %q が Program にない", view.Viewer)}}
	}
	return newEmitter(view, ns, opts), nil
}

// emitter は一度の Emit の状態。
type emitter struct {
	view   *ir.View
	prog   *ir.Program
	ns     *ir.Namespace
	viewer string
	opts   Options
	diags  []diag.Diagnostic

	pkg string // Go のパッケージ名
	dir string // ルートからの出力ディレクトリ（`/` 区切り）: この単位での Dir(viewer) = View.Config.Dir

	declNS    map[string]string // FQN → 宣言を持つ名前空間
	inUnit    map[string]bool   // viewer の宣言のうち、単位の対象のもの（Span.File が View.Files にある。docs/config.md「in」）
	pkgPaths  map[string]string // 別の出力のディレクトリ → import パス
	dirOfPath map[string]string // その逆
	imported  map[string]bool   // 作ったファイルが実際に import した、別の出力のディレクトリ（[Imports]）

	// 出力の対象（docs/emit-go.md「出力の対象」）。select.go が決める。
	sel *selection
	// reach は、出力の対象が参照する型（model / scalar / union / exception）の FQN。名前空間を問わず、参照を辿り切ったもの。
	// viewer の型はこのうちの全部を出す（[Exports]）。
	reach map[string]bool
	// copied は viewer のパッケージに複製する、別の名前空間の型の FQN（docs/emit-go.md「配置」）。
	copied map[string]bool

	// パッケージに出す宣言（viewer の宣言の順、その後に複製を Program の順で）
	models     []*ir.Model
	scalars    []*ir.Scalar
	unions     []*ir.Union
	exceptions []*ir.Exception
	effects    []*ir.Effect
	classifies []*ir.Classify // 値の分類と状態の分類（宣言の順）
	ops        []*ir.Op       // 選ばれた op（宣言の順）
	leaves     []*ir.Op       // Leaves に置く op: 効果を持たない葉と、口だけを出す配線
	units      []*stateUnit   // 状態の単位（宣言の順）
	unitOf     map[string]*stateUnit
	commandOf  map[string]*stateUnit // 効果を持つ葉の op の FQN → その命令を持つ状態の単位

	// 配線を見て集めるもの
	projections []projection // 必要になった射影の組（順序は必要になった順）
	needPtr     bool         // types.go に ptr ヘルパーが要るか

	wrappers map[string][]wrapper // op の FQN → 包む関数（内側から順）

	copyNote string // 複製した宣言を出している間、そのコメントに足す文
}

// projection は model から model への変換関数 <From>To<To>（docs/emit-go.md「配線の本体」の「射影」）。
type projection struct{ from, to string }

func newEmitter(view *ir.View, ns *ir.Namespace, opts Options) *emitter {
	e := &emitter{
		view:      view,
		prog:      view.Program,
		ns:        ns,
		viewer:    view.Viewer,
		opts:      opts,
		declNS:    map[string]string{},
		reach:     map[string]bool{},
		copied:    map[string]bool{},
		inUnit:    map[string]bool{},
		pkgPaths:  map[string]string{},
		dirOfPath: map[string]string{},
		imported:  map[string]bool{},
		unitOf:    map[string]*stateUnit{},
		commandOf: map[string]*stateUnit{},
		wrappers:  map[string][]wrapper{},
	}
	files := map[string]bool{}
	for _, f := range view.Files {
		files[f] = true
	}
	for i := range e.prog.Namespaces {
		n := &e.prog.Namespaces[i]
		for _, d := range n.Decls {
			if d != nil {
				e.declNS[d.Common().Name] = n.Name
				if n.Name == e.viewer && files[d.Common().Span.File] {
					e.inUnit[d.Common().Name] = true
				}
			}
		}
	}
	return e
}

// collect は出力の対象を決め（select.go）、パッケージに出す宣言を集める（decls.go）。ファイルは作らない。
func (e *emitter) collect() {
	e.sel = e.computeSelection()
	e.collectDecls()
}

// run は docs/emit-go.md を上から順に実行する。
func (e *emitter) run() []File {
	e.pkg = gol.PackageName(e.viewer)
	e.dir = dirOf(e.view.Config)
	e.collect()
	if e.sel.empty() {
		return nil // 何も選ばれていない（docs/emit-go.md「出力の対象」）
	}
	if _, err := gol.ImportPath(e.opts.Root, e.dir); err != nil {
		e.errorf(CodeNoGoMod, nil, "名前空間 %s の出力先 %q の上に go.mod がない: %v", e.viewer, e.dir, err)
		return nil
	}
	e.checkNames()

	// 配線と op を先に作り、射影を集める。
	wiring := e.genWiring()
	ops := e.genOps()
	states := e.genStates()
	classify := e.genClassify()
	types := e.genTypes()
	validate := e.genValidate()
	doc := e.genDoc()

	var files []File
	for _, g := range []*genFile{doc, types, validate, ops, states, wiring, classify} {
		if g == nil || g.body.Len() == 0 && g.pkgDoc == "" {
			continue
		}
		if f, ok := e.finish(g); ok {
			files = append(files, f)
			for _, p := range g.imports.Paths() {
				if dir, other := e.dirOfPath[p]; other {
					e.imported[dir] = true
				}
			}
		}
	}
	return files
}

// genFile は作る途中のファイル一つ。imports は GoType が足す。
type genFile struct {
	name    string
	imports gol.Imports
	body    bytes.Buffer
	// pkgDoc は doc.go のパッケージコメント（package 節の直前）。
	pkgDoc string
}

func (e *emitter) newFile(name string) *genFile {
	g := &genFile{name: name}
	g.imports.Viewer = e.viewer
	g.imports.Resolve = e.resolve
	return g
}

func (g *genFile) printf(format string, args ...any) {
	fmt.Fprintf(&g.body, format, args...)
}

func (g *genFile) println(s string) {
	g.body.WriteString(s)
	g.body.WriteByte('\n')
}

// finish はヘッダ・package 節・import を付けて整形する。整形に失敗したら
// 整形前の内容を <out>/.hozoc-failed/<file> に書き、内部エラーの診断を出す。
func (e *emitter) finish(g *genFile) (File, bool) {
	var buf bytes.Buffer
	buf.WriteString(Header)
	buf.WriteString("\n")
	if g.pkgDoc != "" {
		buf.WriteString(g.pkgDoc)
	}
	buf.WriteString("package " + e.pkg + "\n\n")
	if imp := g.imports.Render(); imp != "" {
		buf.WriteString(imp)
		buf.WriteString("\n")
	}
	buf.Write(g.body.Bytes())
	rel := path.Join(e.dir, g.name)
	out, err := format.Source(buf.Bytes())
	if err != nil {
		failed := filepath.Join(e.opts.Root, filepath.FromSlash(e.dir), FailedDir, g.name)
		where := failed
		if werr := os.MkdirAll(filepath.Dir(failed), 0o755); werr == nil {
			if werr = os.WriteFile(failed, buf.Bytes(), 0o644); werr != nil {
				where = fmt.Sprintf("%s（書けなかった: %v）", failed, werr)
			}
		} else {
			where = fmt.Sprintf("%s（書けなかった: %v）", failed, werr)
		}
		e.errorf(CodeInternal, nil, "生成器の不具合: %s を go/format で整形できない: %v。整形前の内容を %s に書いた", rel, err, where)
		return File{}, false
	}
	return File{Path: rel, Content: out}, true
}

// errorf は error の診断を足す。span が nil でなければファイルと位置をメッセージに付ける。
func (e *emitter) errorf(code string, span *ir.Span, format string, args ...any) {
	d := diag.Diagnostic{Severity: diag.Error, Code: code, Message: fmt.Sprintf(format, args...)}
	if span != nil {
		d.File = span.File
		d.Message += fmt.Sprintf("（%s:%d:%d）", span.File, span.Start.Line, span.Start.Col)
	}
	e.diags = append(e.diags, d)
}

// lookup は FQN の宣言。なければ nil。
func (e *emitter) lookup(fqn string) ir.Decl { return e.prog.Lookup(fqn) }

func (e *emitter) model(fqn string) *ir.Model {
	m, _ := e.lookup(fqn).(*ir.Model)
	return m
}

func (e *emitter) scalar(fqn string) *ir.Scalar {
	s, _ := e.lookup(fqn).(*ir.Scalar)
	return s
}

func (e *emitter) union(fqn string) *ir.Union {
	u, _ := e.lookup(fqn).(*ir.Union)
	return u
}

func (e *emitter) op(fqn string) *ir.Op {
	o, _ := e.lookup(fqn).(*ir.Op)
	return o
}

// typeName は FQN の Go の型名（パッケージの修飾なし）。
func (e *emitter) typeName(fqn string) string {
	return gol.TypeName(fqn, e.declNS[fqn])
}

// localName は FQN の最後のセグメント（宣言名）。
func localName(fqn string) string {
	if i := strings.LastIndexByte(fqn, '.'); i >= 0 {
		return fqn[i+1:]
	}
	return fqn
}
